/// Each status's opening motion, ground or air.
unsafe fn change_motion(fighter: &mut L2CFighterCommon, ground_motion: &str, air_motion: &str, end: f32) {
    let m = if ground(fighter) { ground_motion } else { air_motion };
    MotionModule::change_motion(fighter.module_accessor, Hash40::new(m), 0.0, 1.0, false, end, false, false);
}

/// The ground/air swap at the bottom of every main loop: correct, kinetic type, and the same
/// motion carried across at the same frame. `keep_rate` is LOOP's variant; `kinetics` is false
/// only for FAILURE, whose swap does not call FUN_71000131a0. True when a swap happened.
unsafe fn situation_swap(
    fighter: &mut L2CFighterCommon,
    ground_motion: &str,
    air_motion: &str,
    keep_rate: bool,
    kinetics: bool,
) -> bool {
    let boma = fighter.module_accessor;
    let now = fighter.global_table[GT_SITUATION].get_i32();
    let was = fighter.global_table[GT_SITUATION_PREV].get_i32();
    let (motion, to_ground) = if was != *SITUATION_KIND_GROUND && now == *SITUATION_KIND_GROUND {
        (ground_motion, true)
    } else if was == *SITUATION_KIND_GROUND && now == *SITUATION_KIND_AIR {
        (air_motion, false)
    } else {
        return false;
    };
    if to_ground {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_GROUND_CLIFF_STOP));
        KineticModule::change_kinetic(boma, *FIGHTER_KINETIC_TYPE_GROUND_STOP);
    } else {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_AIR));
        KineticModule::change_kinetic(boma, *FIGHTER_KINETIC_TYPE_AIR_STOP);
        if kinetics {
            air_kinetics(fighter);
        }
    }
    if keep_rate {
        MotionModule::change_motion_inherit_frame_keep_rate(boma, Hash40::new(motion), -1.0, 1.0, 0.0);
    } else {
        MotionModule::change_motion_inherit_frame(boma, Hash40::new(motion), -1.0, 1.0, 0.0, false, false);
    }
    true
}

/// LOOP and WAIT both shoot on any stick tilt: SHOOT_FRONT when the tilt is the way he faces.
unsafe fn shoot_on_tilt(fighter: &mut L2CFighterCommon) -> bool {
    let boma = fighter.module_accessor;
    let x = fighter.global_table[GT_STICK_X].get_f32();
    if x == 0.0 {
        return false;
    }
    let lr = PostureModule::lr(boma);
    if (lr == 1.0 && x > 0.0) || (lr == -1.0 && x < 0.0) {
        WorkModule::on_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_SHOOT_FRONT);
    }
    fighter.change_status(RAT_STATUS_KIND_SPECIAL_N_SHOOT.into(), false.into());
    true
}

/// SHOOT, END, HIT_END and FAILURE all finish the same way: in the cancel window, the common
/// ground and air checks; at the motion's end, WAIT or FALL; otherwise the situation swap.
unsafe fn finish_loop(fighter: &mut L2CFighterCommon, ground_motion: &str, air_motion: &str, kinetics: bool) -> L2CValue {
    if CancelModule::is_enable_cancel(fighter.module_accessor) {
        if fighter.sub_wait_ground_check_common(false.into()).get_bool() {
            return 0.into();
        }
        if fighter.sub_air_check_fall_common().get_bool() {
            return 0.into();
        }
    }
    if MotionModule::is_end(fighter.module_accessor) {
        let next = if ground(fighter) { *FIGHTER_STATUS_KIND_WAIT } else { *FIGHTER_STATUS_KIND_FALL };
        fighter.change_status(next.into(), false.into());
        return 0.into();
    }
    situation_swap(fighter, ground_motion, air_motion, false, kinetics);
    0.into()
}

