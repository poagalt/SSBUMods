unsafe fn push_i(fighter: &mut L2CFighterCommon, v: i32) {
    fighter.push_lua_stack(&mut L2CValue::new_int(v as u64));
}

unsafe fn push_f(fighter: &mut L2CFighterCommon, v: f32) {
    fighter.push_lua_stack(&mut L2CValue::new_num(v));
}

/// FUN_71000131a0: the air kinetics -- gravity accel and cap, and the stop energy's brake.
unsafe fn air_kinetics(fighter: &mut L2CFighterCommon) {
    let boma = fighter.module_accessor;
    if fighter.global_table[GT_SITUATION] != *SITUATION_KIND_AIR {
        return;
    }
    let accel = param_f(boma, "air_accel_y");
    fighter.clear_lua_stack();
    push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
    push_f(fighter, -accel);
    sv_kinetic_energy::set_accel(fighter.lua_state_agent);
    let max = param_f(boma, "air_speed_y_max");
    fighter.clear_lua_stack();
    push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
    push_f(fighter, max);
    sv_kinetic_energy::set_limit_speed(fighter.lua_state_agent);
    fighter.clear_lua_stack();
    push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
    push_f(fighter, max);
    sv_kinetic_energy::set_stable_speed(fighter.lua_state_agent);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
    let brake = param_f(boma, "air_brake_x");
    fighter.clear_lua_stack();
    push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_STOP);
    push_f(fighter, brake);
    push_f(fighter, 0.0);
    sv_kinetic_energy::set_brake(fighter.lua_state_agent);
}

unsafe fn reset_energy(fighter: &mut L2CFighterCommon, energy: i32, kind: i32) {
    fighter.clear_lua_stack();
    push_i(fighter, energy);
    push_i(fighter, kind);
    for _ in 0..5 {
        push_f(fighter, 0.0);
    }
    sv_kinetic_energy::reset_energy(fighter.lua_state_agent);
}

/// FUN_71000127e0: the init kinetics SPECIAL_N and FAILURE share.
unsafe fn init_kinetics(fighter: &mut L2CFighterCommon) {
    let boma = fighter.module_accessor;
    let air = fighter.global_table[GT_SITUATION] == *SITUATION_KIND_AIR;
    let mut sx = KineticModule::get_sum_speed_x(boma, *KINETIC_ENERGY_RESERVE_ATTRIBUTE_MAIN);
    let mut sy = KineticModule::get_sum_speed_y(boma, *KINETIC_ENERGY_RESERVE_ATTRIBUTE_MAIN);
    if air {
        sx *= param_f(boma, "start_air_speed_x_mul");
        sy *= param_f(boma, "start_air_speed_y_mul");
    }
    KineticModule::unable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_CONTROL);
    KineticModule::unable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_MOTION);
    if air {
        reset_energy(fighter, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY, *ENERGY_GRAVITY_RESET_TYPE_GRAVITY);
        fighter.clear_lua_stack();
        push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
        push_f(fighter, sy);
        sv_kinetic_energy::set_speed(fighter.lua_state_agent);
        KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_GRAVITY);
    }
    let stop = if air { *ENERGY_STOP_RESET_TYPE_AIR } else { *ENERGY_STOP_RESET_TYPE_GROUND };
    reset_energy(fighter, *FIGHTER_KINETIC_ENERGY_ID_STOP, stop);
    fighter.clear_lua_stack();
    push_i(fighter, *FIGHTER_KINETIC_ENERGY_ID_STOP);
    push_f(fighter, sx);
    push_f(fighter, 0.0);
    sv_kinetic_energy::set_speed(fighter.lua_state_agent);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_STOP);
    reset_energy(fighter, *FIGHTER_KINETIC_ENERGY_ID_DAMAGE, *ENERGY_STOP_RESET_TYPE_FREE);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_DAMAGE);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_GROUND_MOVEMENT);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_JOSTLE);
    KineticModule::enable_energy(boma, *FIGHTER_KINETIC_ENERGY_ID_ENV_WIND);
    air_kinetics(fighter);
}

