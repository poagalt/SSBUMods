unsafe fn shoot_motions(fighter: &mut L2CFighterCommon) -> (&'static str, &'static str) {
    if WorkModule::is_flag(fighter.module_accessor, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_SHOOT_FRONT) {
        ("special_n_shoot_f", "special_air_n_shoot_f")
    } else {
        ("special_n_shoot_b", "special_air_n_shoot_b")
    }
}

unsafe extern "C" fn shoot_main(fighter: &mut L2CFighterCommon) -> L2CValue {
    let boma = fighter.module_accessor;
    let (g, a) = shoot_motions(fighter);
    change_motion(fighter, g, a, 0.0);
    let mul = spikeball_speed_mul(fighter);
    WorkModule::set_float(boma, mul, *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_SPIKEBALL_SPEED_MUL);
    LinkModule::send_event_nodes(boma, *LINK_NO_ARTICLE, Hash40::new_raw(0x1e11a405f1), 0);
    if LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT) {
        ball_to(fighter, *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_WAIT);
    }
    update_spikeball_pos(fighter);
    if StatusModule::prev_status_kind(boma, 0) == RAT_STATUS_KIND_SPECIAL_N_WAIT {
        WorkModule::on_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_SHOOT_PREVIOUS_WAIT);
    }
    let dx = (PostureModule::pos_x(boma)
        - WorkModule::get_float(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_START_SPIKEBALL_POS_X)).abs();
    let dy = (PostureModule::pos_y(boma)
        - WorkModule::get_float(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_START_SPIKEBALL_POS_Y)).abs();
    let dist = (dx * dx + dy * dy).sqrt();
    WorkModule::set_float(boma, dist, *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_START_SPIKEBALL_DISTANCE);
    crate::telemetry::sink::diag(format!(
        "[rat] PTOOIE p{} SHOOT front={} speed_mul={mul:.3} dist={dist:.2}",
        entry_of(boma),
        WorkModule::is_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_SHOOT_FRONT)
    ));
    fighter.sub_shift_status_main(L2CValue::Ptr(shoot_main_loop as *const () as _))
}

unsafe extern "C" fn shoot_main_loop(fighter: &mut L2CFighterCommon) -> L2CValue {
    if mouth_caught_ball(fighter) {
        fighter.change_status(RAT_STATUS_KIND_SPECIAL_N_END.into(), false.into());
        return 0.into();
    }
    let (g, a) = shoot_motions(fighter);
    finish_loop(fighter, g, a, true)
}

