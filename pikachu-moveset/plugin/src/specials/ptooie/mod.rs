unsafe extern "C" fn special_n_pre(fighter: &mut L2CFighterCommon) -> L2CValue {
    fighter.sub_status_pre_SpecialNCommon();
    let generatable = ball().map_or(false, |id| ArticleModule::is_generatable(fighter.module_accessor, id));
    if !generatable {
        StatusModule::set_status_kind_interrupt(fighter.module_accessor, RAT_STATUS_KIND_SPECIAL_N_FAILURE);
        return 1.into();
    }
    pre_common(
        fighter,
        keep_none(),
        (*FIGHTER_LOG_MASK_FLAG_ATTACK_KIND_SPECIAL_N | *FIGHTER_LOG_MASK_FLAG_ACTION_CATEGORY_ATTACK
            | *FIGHTER_LOG_MASK_FLAG_ACTION_TRIGGER_ON | *FIGHTER_LOG_MASK_FLAG_SHOOT) as u64,
        (*FIGHTER_STATUS_ATTR_DISABLE_TURN_DAMAGE | *FIGHTER_STATUS_ATTR_START_TURN) as u32,
    );
    0.into()
}

unsafe extern "C" fn special_n_init(fighter: &mut L2CFighterCommon) -> L2CValue {
    init_kinetics(fighter);
    0.into()
}

unsafe extern "C" fn special_n_main(fighter: &mut L2CFighterCommon) -> L2CValue {
    let boma = fighter.module_accessor;
    if ground(fighter) {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_GROUND_CLIFF_STOP));
    } else {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_AIR));
    }
    change_motion(fighter, "special_n_start", "special_air_n_start", 0.0);
    WorkModule::set_float(boma, PostureModule::scale(boma), *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_START_SCALE);
    crate::telemetry::sink::diag(format!(
        "[rat] PTOOIE p{} SPECIAL_N main: ground={} ball_article={:?}",
        entry_of(boma), ground(fighter), ball()
    ));
    fighter.sub_shift_status_main(L2CValue::Ptr(special_n_main_loop as *const () as _))
}

unsafe extern "C" fn special_n_main_loop(fighter: &mut L2CFighterCommon) -> L2CValue {
    let boma = fighter.module_accessor;
    if WorkModule::is_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_GENERATE_ARTICLE_SPIKEBALL) {
        if let Some(id) = ball() {
            ArticleModule::generate_article(boma, id, false, -1);
            crate::telemetry::sink::diag(format!(
                "[rat] PTOOIE p{} ball generated: exist={}", entry_of(boma), ArticleModule::is_exist(boma, id)
            ));
            ball_life_check(boma);
        }
        WorkModule::off_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_FLAG_GENERATE_ARTICLE_SPIKEBALL);
    }
    if ball_boma(boma).is_some() && !ball_in_step(fighter) {
        to_hit_end(fighter, "special_n_main_loop");
        return 0.into();
    }
    if MotionModule::is_end(boma) {
        fighter.change_status(RAT_STATUS_KIND_SPECIAL_N_LOOP.into(), false.into());
        return 0.into();
    }
    if situation_swap(fighter, "special_n_start", "special_air_n_start", false, true)
        && ball_boma(boma).is_some()
        && LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT)
    {
        if let Some(id) = ball() {
            let m = if ground(fighter) { "start" } else { "start_air" };
            ArticleModule::change_motion(boma, id, Hash40::new(m), true, -1.0);
        }
    }
    0.into()
}

/// `SpecialN_end`: unless the next status is LOOP, tell the ball (event 0x1d705643d2, which the
/// ball's own class handles).
unsafe extern "C" fn special_n_end(fighter: &mut L2CFighterCommon) -> L2CValue {
    // `global_table[0xb]`, the INCOMING status -- what the source compares (its `this[...]` read),
    // and the read src/specials/specialhi and ../shoulder already make in their End lines. This
    // used `StatusModule::status_kind_next`; both are logged until a playtest shows they agree.
    let next = fighter.global_table[0xb].get_i32();
    let send = next != RAT_STATUS_KIND_SPECIAL_N_LOOP;
    crate::telemetry::sink::diag(format!(
        "[rat] PTOOIE p{} SPECIAL_N end: incoming {next:#x}, status_kind_next {:#x} -> {}",
        entry_of(fighter.module_accessor),
        StatusModule::status_kind_next(fighter.module_accessor),
        if send { "ball told to end (0x1d705643d2)" } else { "ball kept for the blow" }
    ));
    if send {
        LinkModule::send_event_nodes(fighter.module_accessor, *LINK_NO_ARTICLE, Hash40::new_raw(0x1d705643d2), 0);
    }
    0.into()
}

