const GT_SITUATION: i32 = 0x16;
const GT_SITUATION_PREV: i32 = 0x17;
/// `globalTable[0x1a]`, the engine's cached stick x (see ../shoulder for where that is settled).
const GT_STICK_X: i32 = 0x1a;

const PARAM_SPECIAL_N: u64 = 0x0f_8991_92aa;

/// The ball is the article row `spikeball`. Every call goes through this, so a row that is off
/// makes the move a FAILURE rather than a call with a wrong id.
fn ball() -> Option<i32> {
    crate::articles::article_id("spikeball")
}

unsafe fn entry_of(boma: *mut BattleObjectModuleAccessor) -> usize {
    let e = WorkModule::get_int(boma, *FIGHTER_INSTANCE_WORK_ID_INT_ENTRY_ID) as usize;
    if e >= 8 { 0 } else { e }
}

unsafe fn param_f(boma: *mut BattleObjectModuleAccessor, key: &str) -> f32 {
    WorkModule::get_param_float(boma, PARAM_SPECIAL_N, smash::hash40(key))
}

unsafe fn param_i(boma: *mut BattleObjectModuleAccessor, key: &str) -> i32 {
    WorkModule::get_param_int(boma, PARAM_SPECIAL_N, smash::hash40(key))
}

unsafe fn ground(fighter: &mut L2CFighterCommon) -> bool {
    fighter.global_table[GT_SITUATION] == *SITUATION_KIND_GROUND
}

unsafe fn ball_boma(boma: *mut BattleObjectModuleAccessor) -> Option<*mut BattleObjectModuleAccessor> {
    let id = ball()?;
    if !ArticleModule::is_exist(boma, id) {
        return None;
    }
    crate::articles::accessor(boma, id)
}

/// EVERY WAY INTO HIT_END GOES THROUGH HERE, and says why. Playtest 2026-10-18: every Ptooie went
/// SPECIAL_N -> LOOP -> HIT_END on the blow's first frame, the ball gone in a puff, and the log had
/// only "HIT_END" -- not which test failed, nor what the ball was doing.
unsafe fn to_hit_end(fighter: &mut L2CFighterCommon, from: &str) {
    let boma = fighter.module_accessor;
    let ball_st = match ball_boma(boma) {
        Some(b) => format!("{:#x} motion {:#x}", StatusModule::status_kind(b), MotionModule::motion_kind(b)),
        None => "gone".to_string(),
    };
    crate::telemetry::sink::diag(format!(
        "[rat] PTOOIE p{} -> HIT_END from {from}: linked={} ball={ball_st} stop={}",
        entry_of(boma),
        LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT),
        StopModule::is_stop(boma)
    ));
    fighter.change_status(RAT_STATUS_KIND_SPECIAL_N_HIT_END.into(), false.into());
}

/// THE BALL'S LIFE, CHECKED THE MOMENT IT EXISTS. Its lua counts WEAPON_INSTANCE_WORK_ID_INT_LIFE
/// down each frame and removes itself at 0, and only its NATIVE init sets it, from
/// `param_spikeball.life`. tools/gen-vlprc.sh now ships that object for smashline to answer the read
/// with; this says whether it did. If the ball is born with no life anyway, it is given Piranha
/// Plant's own number from the same object (src/params/ptooie.rs) rather than a move that cannot
/// be used -- and says so, because that means the vl.prc route did not reach the native read.
unsafe fn ball_life_check(boma: *mut BattleObjectModuleAccessor) {
    let Some(b) = ball_boma(boma) else {
        return;
    };
    let life = WorkModule::get_int(b, *WEAPON_INSTANCE_WORK_ID_INT_LIFE);
    if life > 0 {
        crate::telemetry::sink::diag(format!("[rat] PTOOIE p{} ball born with life {life}", entry_of(boma)));
        return;
    }
    let param = crate::params::spikeball_param(smash::hash40("life")).unwrap_or(120.0) as i32;
    WorkModule::set_int(b, param, *WEAPON_INSTANCE_WORK_ID_INT_LIFE);
    crate::telemetry::sink::diag(format!(
        "[rat] PTOOIE p{} ball born with life {life} -- the native read of param_spikeball.life did \
         not reach the shipped vl.prc; set to Piranha Plant's {param}",
        entry_of(boma)
    ));
}

