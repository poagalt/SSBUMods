/// `FighterSpecializer_Packun::is_special_n_spikeball_changed_status`, with OUR status numbers.
/// TRUE when the ball is in step with the fighter.
unsafe fn ball_in_step(fighter: &mut L2CFighterCommon) -> bool {
    let boma = fighter.module_accessor;
    if !LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT) {
        return false;
    }
    let Some(b) = ball_boma(boma) else {
        return false;
    };
    let ours = StatusModule::status_kind(boma);
    let theirs = StatusModule::status_kind(b);
    (ours == *FIGHTER_STATUS_KIND_SPECIAL_N && theirs == *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_START)
        || (ours == RAT_STATUS_KIND_SPECIAL_N_LOOP && theirs == *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_LOOP)
        || (ours == RAT_STATUS_KIND_SPECIAL_N_WAIT && theirs == *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_WAIT)
}

/// HIS SEARCH-HIT HANDLER, which is the only way into END, and which never runs for a Pikachu.
///
/// Nothing in lua2cpp_packun changes status to FIGHTER_PACKUN_STATUS_KIND_SPECIAL_N_END (0x1e4):
/// its one mention is the status registration. The way in is native, two functions of Piranha
/// Plant's own fighter callback table (13.0.5 main, table at 0x5000380):
///
///   sub_e0c850 (slot at 0x50003a8), a search-hit handler: if he is in SPECIAL_N_WAIT or _SHOOT,
///     the hit is of kind 1, its sender is a weapon of kind 0x1e8 (WEAPON_KIND_PACKUN_SPIKEBALL)
///     and that weapon's status int 0x1000000a is HIS battle object id, it raises
///     FLAG_SPECIAL_N_WAIT_END (0x200000e1).
///   sub_e0ca50 (0x50003b0), every frame: if that flag is up, clear it and
///     change_status_request(SPECIAL_N_END).
///
/// The search is the SEARCH box his wait and shot scripts open over his mouth, and the ball in its
/// own wait carries a radius-5 ATTACK on its `top` and falls under its wait gravity -- so this is
/// the ball dropping back into his mouth, and END is the swallow. A Pikachu's search hits go to
/// Pikachu's own callback, so the same three tests are made here, the collision itself as the
/// overlap of that box with the ball's hitbox. The flag is not written: 0x200000e1 is one of
/// Pikachu's own instance ids, and nothing else reads it here.
unsafe fn mouth_caught_ball(fighter: &mut L2CFighterCommon) -> bool {
    let boma = fighter.module_accessor;
    // Only while the box is open: the shot clears it on frame 10, and its two near bands have
    // already released the ball on frame 8.
    if !SearchModule::is_search(boma, 0) {
        return false;
    }
    let Some(b) = ball_boma(boma) else {
        return false;
    };
    if WorkModule::get_int(b, 0x1000000a) as u32 != (*boma).battle_object_id {
        return false;
    }
    // His box, at Pikachu's scale: radius 4 from 7 to 8 over `top`, scaled like the script's.
    let k = acmd::SEARCH_SCALE * PostureModule::scale(boma);
    let (r, y1, y2) = (4.0 * k, 7.0 * k, 8.0 * k);
    let (fx, fy) = (PostureModule::pos_x(boma), PostureModule::pos_y(boma));
    let (bx, by) = (PostureModule::pos_x(b), PostureModule::pos_y(b));
    // The ball's own hitbox, its game_wait's ATTACK on `top`.
    let ball_r = 5.0 * PostureModule::scale(b);
    let dy = if by < fy + y1 { fy + y1 - by } else if by > fy + y2 { by - (fy + y2) } else { 0.0 };
    let dx = bx - fx;
    let gap = (dx * dx + dy * dy).sqrt() - (r + ball_r);
    if gap <= 0.0 {
        crate::telemetry::sink::diag(format!(
            "[rat] PTOOIE p{} ball back in the mouth in {:#x} (ball at {dx:+.2},{:+.2} from top) -> END",
            entry_of(boma), StatusModule::status_kind(boma), by - fy
        ));
    }
    gap <= 0.0
}

/// `FighterSpecializer_Packun::get_special_n_spikeball_speed_mul`.
unsafe fn spikeball_speed_mul(fighter: &mut L2CFighterCommon) -> f32 {
    let boma = fighter.module_accessor;
    let Some(b) = ball_boma(boma) else {
        return 1.0;
    };
    let st = StatusModule::status_kind(b);
    let t = if st == *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_LOOP {
        MotionModule::frame(b)
    } else if st == *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_WAIT {
        WorkModule::get_float(b, 0x1000002)
    } else {
        return 1.0;
    };
    let frames = param_i(boma, "loop_down_motion_frame");
    if t >= frames as f32 {
        return 1.0;
    }
    let ratio = if frames > 0 && t > 0.0 { t / frames as f32 } else { 0.0 };
    let min = param_f(boma, "shoot_moveup_speed_mul");
    min + ratio * (1.0 - min)
}

/// `FighterSpecializer_Packun::update_special_n_spikeball_pos`.
unsafe fn update_spikeball_pos(fighter: &mut L2CFighterCommon) {
    let boma = fighter.module_accessor;
    if let Some(b) = ball_boma(boma) {
        WorkModule::set_float(
            boma, PostureModule::pos_x(b),
            *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_START_SPIKEBALL_POS_X,
        );
        WorkModule::set_float(
            boma, PostureModule::pos_y(b),
            *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLOAT_SHOOT_START_SPIKEBALL_POS_Y,
        );
    }
}

/// His `notify_event_msc_cmd(0x2e70a9644c, status)` handler: the ball to `status`, unless it is
/// there already or hopping.
unsafe fn ball_to(fighter: &mut L2CFighterCommon, status: i32) {
    let boma = fighter.module_accessor;
    let (Some(id), Some(b)) = (ball(), ball_boma(boma)) else {
        return;
    };
    let st = StatusModule::status_kind(b);
    if st != status && st != *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_HOP {
        let target = ArticleOperationTarget(*ARTICLE_OPE_TARGET_ALL);
        ArticleModule::change_status(boma, id, status, target);
    }
}

