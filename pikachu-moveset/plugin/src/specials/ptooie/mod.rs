unsafe extern "C" fn end_main(fighter: &mut L2CFighterCommon) -> L2CValue {
    let boma = fighter.module_accessor;
    if StatusModule::prev_status_kind(boma, 0) == RAT_STATUS_KIND_SPECIAL_N_SHOOT {
        WorkModule::on_flag(boma, *FIGHTER_PACKUN_STATUS_SPECIAL_N_WORK_FLAG_END_PREVIOUS_SHOOT);
    }
    if ground(fighter) {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_GROUND_CLIFF_STOP));
    } else {
        GroundModule::correct(boma, GroundCorrectKind(*GROUND_CORRECT_KIND_AIR));
    }
    change_motion(fighter, "special_n_end", "special_air_n_end", 0.0);
    if ball_boma(boma).is_some() && LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT) {
        if let Some(id) = ball() {
            ArticleModule::change_status(
                boma,
                id,
                *WEAPON_PACKUN_SPIKEBALL_STATUS_KIND_END,
                ArticleOperationTarget(*ARTICLE_OPE_TARGET_ALL),
            );
        }
    }
    fighter.sub_shift_status_main(L2CValue::Ptr(end_main_loop as *const () as _))
}

unsafe extern "C" fn end_main_loop(fighter: &mut L2CFighterCommon) -> L2CValue {
    finish_loop(fighter, "special_n_end", "special_air_n_end", true)
}

/// `SpecialNEnd_end`, on EXIT: a ball still linked goes with the move.
unsafe extern "C" fn end_exit(fighter: &mut L2CFighterCommon) -> L2CValue {
    let boma = fighter.module_accessor;
    if LinkModule::is_linked(boma, *WEAPON_LINK_NO_CONSTRAINT) {
        if let Some(id) = ball() {
            ArticleModule::remove_exist(boma, id, ArticleOperationTarget(*ARTICLE_OPE_TARGET_ALL));
        }
    }
    0.into()
}

