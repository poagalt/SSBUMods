// PIRANHA PLANT'S PTOOIE, transcribed onto Pikachu's neutral-B (2026-10-18), replacing Samus's
// Charge Shot.
//
// THE SOURCE. Seven statuses, read in full from the named decompiles in
// vendor/ssbu-status-all/ghidra_scripts/lua2cpp_packun.nro/packun/packun/status/SpecialN*, plus
// the two local helpers they call (FUN_71000127e0, the init kinetics, and FUN_71000131a0, the air
// kinetics -- work/ghidra/packun-717c2.annotated.c) and the three native FighterSpecializer_Packun
// helpers (work/ghidra/main-ee72.annotated.c). docs/the-ptooie.md is the reference sheet.
//
//   SPECIAL_N   (common 0x1DC)  special_n_start      raises the ball (ACMD frame 10 sets GENERATE)
//   LOOP        (ours 0x207)    special_n_blow       blowing it aloft while B is held
//   WAIT        (ours 0x208)    special_n_wait       B released: the ball hangs
//   SHOOT       (ours 0x209)    special_n_shoot_f/b  a stick tilt in LOOP or WAIT fires it
//   END         (ours 0x20A)    special_n_end
//   HIT_END     (ours 0x20B)    special_n_hit        the ball left step (was hit, hopped, fell)
//   FAILURE     (ours 0x20C)    special_n_failure    no ball could be generated
//
// THE THREE NATIVE HELPERS ARE REPRODUCED, NOT CALLED. They take the FIGHTER, compare its status
// against Piranha Plant's own numbers (0x1DC/0x1E1/0x1E2) and read his param_special_n -- on a
// Pikachu every one of those is wrong. Decompiled:
//   is_special_n_spikeball_changed_status  TRUE WHEN THE BALL IS IN STEP (the name is the game's):
//       ball linked (WEAPON_LINK_NO_CONSTRAINT) and the ball's status is START in SPECIAL_N, LOOP
//       in LOOP, WAIT in WAIT. Every caller goes to HIT_END when it is FALSE.
//   get_special_n_spikeball_speed_mul      shoot_moveup_speed_mul + t/loop_down_motion_frame *
//       (1 - shoot_moveup_speed_mul) while t < loop_down_motion_frame, else 1, where t is the
//       ball's motion frame in its LOOP or its WAIT counter (status float 0x1000002) in its WAIT.
//   update_special_n_spikeball_pos         the ball's x and y into our status floats 8 and 9.
//
// AND TWO OF HIS NATIVE EVENT HANDLERS, which Pikachu's native code does not have:
//   * notify_event_msc_cmd(0x2e70a9644c, WAIT) -- main 0xe0c3f8..0xe0c4d8: unless the ball is
//     already in that status or in HOP, ArticleModule::change_status(SPIKEBALL, WAIT). Reproduced
//     as that call (`ball_to`).
//   * the ball's send_event_parents(0x22958dfe78) -- main 0xe0cb34: an owner in SPECIAL_N, LOOP or
//     WAIT goes to HIT_END (0x1e5). NOT reproduced, because it is redundant here: the ball sends it
//     exactly as it leaves its own START (ceiling touch, to FALL) or enters HOP, and either leaves
//     it out of step, which the per-frame step test below turns into the same HIT_END.
//
// WORK IDS, AS ADR 0006 SPLITS THEM. His STATUS ids (FIGHTER_PACKUN_STATUS_SPECIAL_N_*, flags
// 0x2100000B..10, floats 0x1000006..0B) are used directly: they sit inside Pikachu's own
// status-work range and no Pikachu code runs in these statuses. His one INSTANCE id,
// FLAG_SPECIAL_N_WAIT_END (0x200000E1), is only ever CLEARED by these statuses and set by native
// code that does not run for a Pikachu, so it is dropped rather than written into Pikachu's
// instance block.
//
// END DOES NOT FIRE FOR A STATUS KIND THAT IS NOT THE FIGHTER'S OWN (tools/check-statuslines.sh),
// so his END lines on the six new kinds are registered as EXIT. SPECIAL_N is common, so its End
// stays End.
//
// THE SHOT'S GAME SCRIPT IS IN acmd.rs, transcribed from the binary; every other Ptooie script is
// generated by tools/gen-moves.sh.
