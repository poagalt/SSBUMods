unsafe extern "C" fn wait_main_loop(fighter: &mut L2CFighterCommon) -> L2CValue {
    if mouth_caught_ball(fighter) {
        fighter.change_status(RAT_STATUS_KIND_SPECIAL_N_END.into(), false.into());
        return 0.into();
    }
    if !ball_in_step(fighter) {
        to_hit_end(fighter, "wait_main_loop");
        return 0.into();
    }
    if shoot_on_tilt(fighter) {
        return 0.into();
    }
    situation_swap(fighter, "special_n_wait", "special_air_n_wait", false, true);
    0.into()
}

