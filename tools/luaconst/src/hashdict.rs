// EVERY IDENTIFIER-LIKE STRING IN A BINARY, WITH ITS hash40.
//
// WHY THIS EXISTS. Half of what the game's status code passes around is a hash40 and nothing else:
// `LinkModule::send_event_nodes(boma, LINK_NO_CAPTURE, 0x8af9b3d1d, 0)` is how Donkey Kong tells
// the fighter on his shoulder to be carried, and a 40-bit hash is not a name. The usual answer is
// a dictionary -- `vendor/Hashes.txt` has 149,871 entries and resolved the motion and event names
// this project needed for the carry -- but it is a community list of FILE PATHS and params, and
// the names it does not have it will never have. Two keys into the damage-info table that Donkey
// Kong's carry reads, 0x10d723eebb and 0xdc56470f9, are not in it, and guessing at plausible
// spellings produced nothing.
//
// The game itself has the strings. `main`'s `.rodata` holds the lua_const names -- that is how
// `FIGHTER_STATUS_KIND_SWING_GAOGAEN_CATCHED` was found at offset 9,149,415 -- and it holds the
// hash40 source strings for the same reason: something has to have written them down.
//
// So: take every run of identifier characters in the image, hash it, and print the pairs. It is a
// rainbow table over the only vocabulary that matters, the game's own, and it is generated from a
// file already in vendor/main/ with no console involved.
//
// A hash appearing more than once is a collision between two spellings of the same thing (hash40
// is CRC32 plus a length byte, so real collisions are possible but rare); every candidate is
// printed and the reader picks by context.
use std::collections::HashMap;

fn crc32_table() -> [u32; 256] {
    let mut t = [0u32; 256];
    for i in 0..256usize {
        let mut c = i as u32;
        for _ in 0..8 {
            c = if c & 1 != 0 { 0xEDB8_8320 ^ (c >> 1) } else { c >> 1 };
        }
        t[i] = c;
    }
    t
}

/// hash40: CRC32 of the bytes in the low 32 bits, the byte length in the top byte.
fn hash40(s: &[u8], t: &[u32; 256]) -> u64 {
    let mut c: u32 = 0xFFFF_FFFF;
    for &b in s {
        c = t[((c as u8) ^ b) as usize] ^ (c >> 8);
    }
    ((s.len() as u64) << 32) | (c ^ 0xFFFF_FFFF) as u64
}

fn ident(b: u8) -> bool {
    b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_'
}

pub fn run(a: &[String]) {
    if a.is_empty() {
        eprintln!("usage: luaconst --hashdict <image> [<image> ...]");
        std::process::exit(2);
    }
    let t = crc32_table();
    // Keyed by hash so a repeated string costs nothing, with every distinct spelling kept.
    let mut out: HashMap<u64, Vec<String>> = HashMap::new();
    let mut scanned = 0usize;
    for path in a {
        let bytes = match std::fs::read(path) {
            Ok(b) => b,
            Err(e) => {
                eprintln!("; {path}: {e}");
                continue;
            }
        };
        eprintln!("; {path}: {} bytes", bytes.len());
        let mut i = 0usize;
        while i < bytes.len() {
            if !ident(bytes[i]) {
                i += 1;
                continue;
            }
            let start = i;
            while i < bytes.len() && ident(bytes[i]) {
                i += 1;
            }
            // hash40 names in this game run from 2 to about 60 characters. The floor drops the
            // noise that any 22 MB of data contains; the ceiling is a sanity bound.
            let len = i - start;
            if !(2..=64).contains(&len) {
                continue;
            }
            scanned += 1;
            let s = &bytes[start..i];
            let h = hash40(s, &t);
            let name = String::from_utf8_lossy(s).into_owned();
            let e = out.entry(h).or_default();
            if !e.contains(&name) {
                e.push(name);
            }
        }
    }
    eprintln!("; {scanned} candidate string(s), {} distinct hash(es)", out.len());
    println!("# hash40 -> every identifier-like string in the image that produces it");
    println!("# generated by tools/luaconst --hashdict; see src/hashdict.rs for why");
    let mut keys: Vec<_> = out.into_iter().collect();
    keys.sort();
    for (h, names) in keys {
        println!("{h:#x} {}", names.join(" "));
    }
}
