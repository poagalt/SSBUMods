#!/usr/bin/env bash
# Generate the status-kind name table the telemetry prints, from the game's own constant list.
#
# WHY GENERATED. `probe::status_name` was a hand-written match of about twenty entries and two of
# them were WRONG -- it named 56 CATCH_PULL and 57 CATCH_WAIT, and four rounds of logs were read
# through that before a native Donkey Kong trace exposed it. Every other number printed bare, as
# `0x49` or `34(=0x22)`, and each one cost a lookup or, worse, a guess. "I don't want inference of
# any kind, reasonable or not."
#
# THE VALUES ARE LITERALS IN THE CRATE -- `FIGHTER_STATUS_KIND_LANDING: 0x16` -- so this is a
# plain sorted const array and the lookup is a binary search with no runtime setup at all.
#
# ONLY `FIGHTER_STATUS_KIND_*`, anchored. Matching the name loosely also catches
# `FIGHTER_MIIFIGHTER_STATUS_KIND_FINAL_ATTACK` and every other fighter-namespaced kind, which
# are a DIFFERENT numbering that would collide with the common one and mislabel it. That is also
# what `tools/check-status.sh` forbids the plugin from naming at all.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
OUT=pikachu-moveset/plugin/src/telemetry/statusnames.rs
CRATE=$(ls /c/Users/poaga/.cargo/git/checkouts/skyline-smash-*/*/src/lua_const.rs 2>/dev/null | head -1)
[ -n "$CRATE" ] || { echo "cannot find the smash crate's lua_const.rs" >&2; exit 1; }

grep -oE "^[[:space:]]*FIGHTER_STATUS_KIND_[A-Z0-9_]+:[[:space:]]*(0x[0-9a-fA-F]+|[0-9]+)," "$CRATE" \
  | sed 's/^[[:space:]]*//; s/,$//' | sort -u > /tmp/gsn
n=$(wc -l < /tmp/gsn)
[ "$n" -gt 100 ] || { echo "only $n status kinds parsed -- the crate's format changed" >&2; exit 1; }

{
cat <<HEADER
// @generated by tools/gen-statusnames.sh -- do not hand-edit.
//
// Every common FIGHTER_STATUS_KIND the smash crate defines, with the value it
// defines. See the generator for why this is not written by hand: the table it replaces had THREE
// wrong entries and four rounds of logs were read through them.

/// Sorted by kind, so the lookup below is a binary search over a static.
static NAMES: &[(i32, &str)] = &[
HEADER
sed 's/:[[:space:]]*/ /' /tmp/gsn | while read -r name val; do
    # 0xFFFFFFFF is STATUS_KIND_NONE and the table is i32, so anything past the signed range
    # wraps rather than being dropped -- a status the game names is a status the log should name.
    v=$(printf '%d' "$val"); [ "$v" -gt 2147483647 ] && v=$((v - 4294967296))
    printf '%s %s\n' "$v" "${name#FIGHTER_STATUS_KIND_}"
done | sort -n -k1,1 -u | while read -r val short; do
    printf '    (%s, "%s"),\n' "$val" "$short"
done
cat <<'FOOTER'
];

/// The name for a common status kind, or "" when the game does not define one. This moveset's
/// own kinds are not in the game's table and are named by `probe::status_name`.
pub fn of(kind: i32) -> &'static str {
    match NAMES.binary_search_by_key(&kind, |e| e.0) {
        Ok(i) => NAMES[i].1,
        Err(_) => "",
    }
}
FOOTER
} > "$OUT"

# AND THIS MOVESET'S OWN KINDS, FROM src/specials/status.rs, FOR THE SAME REASON.
#
# The generated table above covers the GAME's statuses and the port's own were left hand-written
# in `probe::status_name`. They were wrong too, and worse: 0x201 was labelled RAT_THROW_F_HI when
# it is RAT_SPECIAL_LW_HIT, so a log line reading `SPECIAL_LW -> SPECIAL_LW_HIT` -- Revenge's
# retaliation firing when it should not -- printed as a cargo up-throw and was read as nonsense.
# Fourth time a remembered status number has misled a diagnosis in this project. There is now no
# status number anywhere in the telemetry that is not generated from its declaration.
{
echo
echo "/// This moveset's own kinds, generated from src/specials/status.rs."
echo "static OWN: &[(i32, &str)] = &["
grep -oE "pub const RAT_STATUS_KIND_[A-Z_0-9]+: i32 = 0x[0-9A-Fa-f]+;" \
    pikachu-moveset/plugin/src/specials/status.rs \
  | sed 's/pub const RAT_STATUS_KIND_//; s/: i32 = /,/; s/;//' \
  | awk -F, '$1 != "NUM" { printf "    (%d, \"RAT_%s\"),\n", strtonum($2), $1 }' \
  | sort -t'(' -k2 -n
echo "];"
echo
echo "/// The name for one of this moveset's own kinds, or \"\"."
echo "pub fn of_own(kind: i32) -> &'static str {"
echo "    for (k, n) in OWN {"
echo "        if *k == kind {"
echo "            return n;"
echo "        }"
echo "    }"
echo "    \"\""
echo "}"
} >> "$OUT"
echo "  plus $(grep -c '^    (' <(grep -A 999 'static OWN' "$OUT")) of this moveset's own"
