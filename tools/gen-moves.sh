    sort "$SOUND_REPORT" | uniq -c | sed 's/^/    /' >&2
    rm -f "$SOUND_REPORT"
    exit 1
fi
rm -f "$SOUND_REPORT"
echo "  sound scripts: every ported label mapped through tools/sound-map.tsv"

# ---- the effect substitutions actually landed ---------------------------------------------------
#
# A STALE OR BROKEN TABLE ROW FAILS SILENTLY, which is the whole reason this block exists. The first
# attempt built the replacement with `gsub` and a regex assembled from the effect name; `(`, `)` and
# `"` went unescaped, the substitution never fired, and the `^sys_` test downstream then dropped the
# effect exactly as if there were no table at all. The generator printed nothing unusual and the
# build passed. So: every row must be observable in the output, or it is a row that does nothing.
if [ -f "$ROOT/tools/effect-subs.tsv" ]; then
    subs_rc=0
    while IFS=$'\t' read -r src_eff sys_eff _reason; do
        case "${src_eff:-#}" in \#*|"") continue ;; esac
        leaked=$(grep -rl "\"$src_eff\"" "$ROOT/pikachu-moveset/plugin/src"/{normals,smashes,aerials,throws,defensive,landings,dodges,specials_acmd}/mod.rs 2>/dev/null || true)
        if [ -n "$leaked" ]; then
            echo "  FAIL effect substitution did not fire: $src_eff is still named in $leaked" >&2
            subs_rc=1
            continue
        fi
        n=$(grep -rc "\"$sys_eff\"" "$ROOT/pikachu-moveset/plugin/src"/{normals,smashes,aerials,throws,defensive,landings,dodges,specials_acmd}/mod.rs 2>/dev/null | awk -F: '{s+=$2} END{print s+0}')
        if [ "${n:-0}" -lt 1 ]; then
            echo "  FAIL effect substitution $src_eff -> $sys_eff produced no call; the row is stale or the move is not ported" >&2
            subs_rc=1
        else
            echo "  substituted $src_eff -> $sys_eff ($n call site(s))"
        fi
    done < "$ROOT/tools/effect-subs.tsv"
    [ "$subs_rc" -eq 0 ] || exit 1
fi

# ---- loop scripts kept their loop ------------------------------------------------------------
#
# THE PARITY GATES CANNOT SEE THIS, and that is how it survived six rounds. Gate 3i compares every
# non-geometric argument against the dump and passes, because the ten rapid-jab hits are identical
# and rotating them changes no argument -- the flattened, loopless dump and the real looping script
# are argument-for-argument the same. What differs is control flow, which nothing compared. So the
# generator asserts it directly: every LOOP_SCRIPTS entry must come out with a `loop {` and with
# `wait_loop_clear` as the last statement inside it, which is the shape of the binary.
for ls in $LOOP_SCRIPTS; do
    f=$(grep -l "fn pikachu_game_${ls}(" "$ROOT/pikachu-moveset/plugin/src"/*/mod.rs 2>/dev/null | head -1)
    [ -z "$f" ] && { echo "  FAIL LOOP_SCRIPTS names $ls but no pikachu_game_$ls was generated" >&2; exit 1; }
    body=$(awk "/fn pikachu_game_${ls}\(/,/^}/" "$f")
    if ! printf '%s\n' "$body" | grep -q "^    loop {"; then
        echo "  FAIL pikachu_game_$ls has no loop -- it will play one cycle of hits and stop" >&2
        exit 1
    fi
    last=$(printf '%s\n' "$body" | grep -vE "acmd_|^\s*}\s*$|^\s*$" | tail -1)
    case "$last" in
        *wait_loop_clear*) echo "  pikachu_game_$ls loops, ending each cycle on wait_loop_clear" ;;
        *) echo "  FAIL pikachu_game_$ls loop does not end on wait_loop_clear (last: $last)" >&2; exit 1 ;;
    esac
done
