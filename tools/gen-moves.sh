#!/usr/bin/env bash
# Generates the plugin's move modules from vanilla ACMD dumps.
#
# Source of truth: vendor/SSBU-Dumped-Scripts/smashline/<lua2cpp_X>/<X>/<Acmd>.txt
# These are the game's own scripts, already converted to smashline Rust. Copying them
# verbatim gives frame-data parity by construction -- there is no transcription step.
#
# Only `game_*` scripts are ported. Pikachu's own `effect_*` scripts are left in place:
# vanilla effect scripts reference fighter-prefixed effect archives, which ADR 0002 forbids.
#
# Regenerate with:  bash tools/gen-moves.sh
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DUMP="$ROOT/vendor/SSBU-Dumped-Scripts/smashline"
OUT="$ROOT/pikachu-moveset/plugin/src"

HEADER='// @generated by tools/gen-moves.sh -- DO NOT EDIT BY HAND.
// Frame data is copied verbatim from the vanilla ACMD dumps; edit the source mapping
// in tools/gen-moves.sh instead.

use {
    smash::{
        lua2cpp::*,
        phx::*,
        app::{sv_animcmd::*, lua_bind::*, *},
        lib::{lua_const::*, L2CValue, L2CAgent},
        hash40
    },
    smash_script::*,
    smashline::{*, Priority::*}
};
'

# slot|source fighter dir|acmd file|acmd function name
NORMALS="
jab (Chrom)|chrom|Attack11|attack11
dash attack (Mythra)|elight|AttackDash|attackdash
f-tilt (Mythra)|elight|AttackS3|attacks3
f-tilt up, shares the s3 game script (Mythra)|=|attacks3hi|attacks3
f-tilt down, shares the s3 game script (Mythra)|=|attacks3lw|attacks3
u-tilt (Falco)|falco|AttackHi3|attackhi3
d-tilt (R.O.B.)|robot|AttackLw3|attacklw3
"

SMASHES="
f-smash (Little Mac)|littlemac|AttackS4|attacks4
f-smash up (Little Mac)|littlemac|AttackS4Hi|attacks4hi
f-smash down (Little Mac)|littlemac|AttackS4Lw|attacks4lw
u-smash (Fox)|fox|AttackHi4|attackhi4
d-smash (Game & Watch)|gamewatch|AttackLw4|attacklw4
"

AERIALS="
n-air (Palutena)|palutena|AttackAirN|attackairn
f-air (Kazuya)|demon|AttackAirF|attackairf
b-air (Cloud)|cloud|AttackAirB|attackairb
u-air (Corrin)|kamui|AttackAirHi|attackairhi
d-air (K. Rool)|krool|AttackAirLw|attackairlw
"

THROWS="
grab (Palutena)|palutena|Catch|catch
dash grab (Palutena)|palutena|CatchDash|catchdash
pivot grab (Palutena)|palutena|CatchTurn|catchturn
pummel (Kazuya)|demon|CatchAttack|catchattack
b-throw (Incineroar)|gaogaen|ThrowB|throwb
u-throw (Mewtwo)|mewtwo|ThrowHi|throwhi
"

DEFENSIVE="
get-up attack, face up (Bowser)|koopa|DownAttackU|downattacku
get-up attack, face down (Bowser)|koopa|DownAttackD|downattackd
trip attack (Bowser)|koopa|SlipAttack|slipattack
ledge attack (Ganondorf)|ganon|CliffAttack|cliffattack
"

emit_module() {
    local modname="$1" spec="$2"
    local file="$OUT/$modname/mod.rs"
    mkdir -p "$OUT/$modname"
    printf '%s\n' "$HEADER" > "$file"

    local installs=""
    while IFS='|' read -r slot fighter acmd fname; do
        [ -z "${slot// }" ] && continue
        if [ "$fighter" = "=" ]; then
            echo "// ---- $slot : game_$acmd -> pikachu_game_$fname ----" >> "$file"
            installs="$installs        .game_acmd(\"game_$acmd\", pikachu_game_$fname, Default)
"
            continue
        fi
        local src="$DUMP/lua2cpp_$fighter/$fighter/$acmd.txt"
        if [ ! -f "$src" ]; then
            echo "MISSING: $slot -> $src" >&2
            continue
        fi
        echo "// ---- $slot : game_$fname ----" >> "$file"
        # Take only the game_ function, rename it, drop effect_/sound_/expression_.
        awk -v want="game_$fname" '
            /^unsafe extern "C" fn / {
                infn = ($5 ~ "^" want "\\(")
            }
            infn { print }
        ' "$src" \
            | sed "s/^unsafe extern \"C\" fn game_$fname(/unsafe extern \"C\" fn pikachu_game_$fname(/" \
            | sed -f "$ROOT/tools/bone-remap.sed" >> "$file"
        echo "" >> "$file"
        installs="$installs        .game_acmd(\"game_$fname\", pikachu_game_$fname, Default)\n"
    done <<< "$spec"

    {
        echo "pub fn install() {"
        echo "    Agent::new(\"pikachu\")"
        printf "%b" "$installs"
        echo "        .install();"
        echo "}"
    } >> "$file"
    echo "generated $modname/mod.rs"
}

emit_module normals   "$NORMALS"
emit_module smashes   "$SMASHES"
emit_module aerials   "$AERIALS"
emit_module throws    "$THROWS"
emit_module defensive "$DEFENSIVE"
