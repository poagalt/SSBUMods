emit_module() {
    local modname="$1" spec="$2"
    local file="$OUT/$modname/mod.rs"
    mkdir -p "$OUT/$modname"
    printf '%s\n' "$HEADER" > "$file"

    local installs=""
    while IFS='|' read -r slot fighter acmd fname; do
        [ -z "${slot// }" ] && continue
        case "$slot" in \#*) continue ;; esac
        if [ "$fighter" = "0" ]; then
            echo "// ---- $slot : empty override of game_$fname ----" >> "$file"
            echo "unsafe extern \"C\" fn pikachu_game_$fname(_agent: &mut L2CAgentBase) {}" >> "$file"
            echo "" >> "$file"
            installs="$installs        .game_acmd(\"game_$fname\", pikachu_game_$fname, Default)
"
            # SOUND_OVERRIDES: Pikachu's own sound script for this motion plays a bank entry that
            # Rat of Doom's bank now holds DONOR audio in (tools/sound-slots.tsv), so it is replaced
            # with a plain landing. Only landingairlw today: his d-air landing burst plays
            # attackair_L01/L02, and Pyra has no landing of her own to port.
            local ov
            ov=$(printf '%s\n' "$SOUND_OVERRIDES" | awk -F'|' -v f="$fname" '$1 == f { print $2 }')
            if [ -n "$ov" ]; then
                echo "// ---- $slot : sound_$fname -> Pikachu's own $ov ----" >> "$file"
                echo "unsafe extern \"C\" fn pikachu_sound_$fname(agent: &mut L2CAgentBase) {" >> "$file"
                echo "    if macros::is_excute(agent) {" >> "$file"
                echo "        macros::PLAY_LANDING_SE(agent, Hash40::new(\"$ov\"));" >> "$file"
                echo "    }" >> "$file"
                echo "}" >> "$file"
                echo "" >> "$file"
                installs="$installs        .sound_acmd(\"sound_$fname\", pikachu_sound_$fname, Default)
"
            fi
            continue
        fi
        if [ "$fighter" = "N" ]; then
            # Null BOTH scripts. Used for a Pikachu script that must never run and has no ported
            # replacement, so an empty override is the whole point rather than a side effect.
            echo "// ---- $slot : empty override of game_$fname AND effect_$fname ----" >> "$file"
            echo "unsafe extern \"C\" fn pikachu_game_$fname(_agent: &mut L2CAgentBase) {}" >> "$file"
            echo "unsafe extern \"C\" fn pikachu_effect_$fname(_agent: &mut L2CAgentBase) {}" >> "$file"
            echo "" >> "$file"
            installs="$installs        .game_acmd(\"game_$fname\", pikachu_game_$fname, Default)
        .effect_acmd(\"effect_$fname\", pikachu_effect_$fname, Default)
"
            continue
        fi
        if [ "$fighter" = "=" ]; then
            # Alias the EFFECT script too, not just the game script. Registering only the game
            # script left Pikachu's effect_attacks3hi and effect_attacks3lw running -- his cheek
            # sparks on Mythra's angled f-tilts.
            echo "// ---- $slot : game_$acmd and effect_$acmd -> pikachu_*_$fname ----" >> "$file"
            installs="$installs        .game_acmd(\"game_$acmd\", pikachu_game_$fname, Default)
        .effect_acmd(\"effect_$acmd\", pikachu_effect_$fname, Default)
        .sound_acmd(\"sound_$acmd\", pikachu_sound_$fname, Default)
"
            continue
        fi
        local src="$DUMP/lua2cpp_$fighter/$fighter/$acmd.txt"
        if [ ! -f "$src" ]; then
            echo "MISSING: $slot -> $src" >&2
            continue
        fi
        echo "// ---- $slot : game_$fname ----" >> "$file"
        # Take only the game_ function, rename it, drop sound_/expression_.
        awk -v want="game_$fname" '
            /^unsafe extern "C" fn / {
                infn = ($5 ~ "^" want "\\(")
            }
            infn { print }
        ' "$src" \
            | sed "s/^unsafe extern \"C\" fn game_$fname(/unsafe extern \"C\" fn pikachu_game_$fname(/" \
              | sed -f "$ROOT/tools/bone-remap.sed" \
              | awk -v loops="$LOOP_SCRIPTS" -v fname="$fname" -f "$ROOT/tools/restore-loop.awk" \
              | awk -v trace="$ACMD_TRACE" -v fname="$fname" '
                  # INSTRUMENTS ONE SCRIPT, named in ACMD_TRACE, and leaves every other byte alone.
                  #
                  # The rapid jab needs to know how many times the VM enters game_attack100 and how
                  # many of those get past wait_loop_clear, which the engine implements as a YIELD
                  # (sv_animcmd::wait_loop_clear, main 0x22b5870). Counting from inside the script
                  # is the only place that can answer it, and it has to come from the GENERATOR
                  # because the module is @generated and a hand edit is wiped by the next build.
                  BEGIN { want = (index(" " trace " ", " " fname " ") > 0) }
                  !want { print; next }
                  /^unsafe extern "C" fn / { print; print "    crate::telemetry::probe::acmd_enter(0);"; blk = 0; next }
                  /wait_loop_clear/ { print; print "    crate::telemetry::probe::acmd_pass(0);"; next }
                  # ONE COUNTER PER is_excute BLOCK, which is the measurement three rounds of
                  # fixes were missing. `acmd_enter` says the script ran; it does NOT say which of
                  # its eleven hit blocks actually executed. A script that runs in full every cycle
                  # and lands one hitbox is indistinguishable, from the outside, from a script that
                  # only runs its first block -- and those need opposite fixes.
                  /if macros::is_excute\(agent\) \{/ {
                      print
                      print "        crate::telemetry::probe::acmd_block(" blk ");"
                      blk = blk + 1
                      next
                  }
                  { print }
              ' >> "$file"
        echo "" >> "$file"
        installs="$installs        .game_acmd(\"game_$fname\", pikachu_game_$fname, Default)\n"

        # An effect script too, ALWAYS -- even if it ends up empty. Without an override, Pikachu's
        # own effect script keeps running on a replaced move, which put pikachu_cheek_elec and
        # pikachu_elec_shock on Little Mac's f-smash, pikachu_tail_arc on Fox's u-smash and
        # Corrin's u-air, and pikachu_elec on Kazuya's f-air: electric sparks on a punch and on a
        # sword. An empty override is strictly better than the wrong effects.
        #
        # The body is GENERATED from the source's `sys_*` spawns rather than copied. See the
        # header of tools/extract-effects.awk: the dumps are not reliably compilable, and
        # salvaging decompiler output does not generalise.
        echo "// ---- $slot : effect_$fname, sys_ effects only (ADR 0002) ----" >> "$file"
        echo "unsafe extern \"C\" fn pikachu_effect_$fname(agent: &mut L2CAgentBase) {" >> "$file"
        awk -v want="effect_$fname" -v subs="$ROOT/tools/effect-subs.tsv" -f "$ROOT/tools/extract-effects.awk" "$src" \
            | sed -f "$ROOT/tools/bone-remap.sed" >> "$file"
        echo "}" >> "$file"
        echo "" >> "$file"
        installs="$installs        .effect_acmd(\"effect_$fname\", pikachu_effect_$fname, Default)\n"

        # And the SOUND script, ALWAYS, for the same reason as the effect script: without an
        # override Pikachu's own sound_ keeps running under the borrowed move -- his swing and his
        # cheek-spark sounds on a Little Mac jab. Generated by tools/extract-sounds.awk with every
        # label through tools/sound-map.tsv; the donor audio those labels now name is put into Rat
        # of Doom's own bank by tools/build-sound-bank.py.
        echo "// ---- $slot : sound_$fname, labels through tools/sound-map.tsv ----" >> "$file"
        echo "unsafe extern \"C\" fn pikachu_sound_$fname(agent: &mut L2CAgentBase) {" >> "$file"
        awk -v want="sound_$fname" -v map="$ROOT/tools/sound-map.tsv" -v loops="$LOOP_SCRIPTS" \
            -v fname="$fname" -f "$ROOT/tools/extract-sounds.awk" "$src" >> "$file" 2>> "$SOUND_REPORT"
        echo "}" >> "$file"
        echo "" >> "$file"
        installs="$installs        .sound_acmd(\"sound_$fname\", pikachu_sound_$fname, Default)\n"
    done <<< "$spec"

    {
        echo "pub fn install() {"
        echo "    crate::charaslot::agent(\"pikachu\")"
        printf "%b" "$installs"
        echo "        .install();"
        echo "}"
    } >> "$file"
    echo "generated $modname/mod.rs"
}

