#!/usr/bin/env bash
# Generates the plugin's move modules from vanilla ACMD dumps.
#
# Source of truth: vendor/SSBU-Dumped-Scripts/smashline/<lua2cpp_X>/<X>/<Acmd>.txt
# These are the game's own scripts, already converted to smashline Rust. Copying them
# verbatim gives frame-data parity by construction -- there is no transcription step.
#
# `game_*` scripts are copied verbatim. `effect_*` scripts are GENERATED from the source's
# `sys_*` spawns only -- see tools/extract-effects.awk for why generating beats filtering, and
# ADR 0002 for why fighter-owned effect archives cannot be used. Leaving Pikachu's own effect
# scripts in place put his electric sparks on a sword swing and a punch.
#
# `sound_*` scripts are GENERATED too (tools/extract-sounds.awk, labels through
# tools/sound-map.tsv). `expression_*` are still Pikachu's. His landing effect scripts are too, and that
# is fine: they only use the generic sys_down_smoke and sys_crown.
#
# Regenerate with:  bash tools/gen-moves.sh
#
# EACH GROUP BELOW IS A DOUBLE-QUOTED SHELL STRING, so a comment inside one MUST NOT contain a
# double quote -- it terminates the string, the remaining lines get executed as commands, and the
# module is silently generated with only the entries before that point. That happened once and the
# only symptom was a stray ": No such file or directory". Use single quotes or none.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DUMP="$ROOT/vendor/SSBU-Dumped-Scripts/smashline"

# SCRIPTS TO INSTRUMENT WITH EXECUTION COUNTERS, space-separated short names. Diagnostic only and
# meant to be emptied once the question is answered -- see the note on `acmd_enter` in
# plugin/src/telemetry/probe.rs. An unknown name is silently ignored, which is the right failure
# for a debugging aid.
ACMD_TRACE="${ACMD_TRACE:-}"

# SCRIPTS WHOSE LOOP THE DUMP LOST -- the dump flattens a do-while(true) into straight-line code,
# rotated by one block. tools/restore-loop.awk puts it back, and its header carries the evidence:
# the disassembled stub and the decompiled loop of Little Mac's real game_attack100.
LOOP_SCRIPTS="${LOOP_SCRIPTS:-attack100}"
OUT="$ROOT/pikachu-moveset/plugin/src"

