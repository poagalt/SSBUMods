#!/usr/bin/env bash
# Stamps the plugin with the commit it was built from, so the LOG says which build produced it.
#
# WHY. "Make sure all your changes took effect" has been answered so far by comparing the .nro's
# byte size against the card, which proves a file was copied and nothing about whether the code in
# it is the code that was just written. A deploy that silently skipped, a build that failed while
# the check grepped for the wrong string, a console that was never restarted -- all three produce
# a playtest of the PREVIOUS build, and all three have happened on this project.
#
# With a stamp, the first line of every log names the commit. If it is not HEAD, the round is
# invalid and tools/analyze.sh says so before anything else is read.
#
# Regenerate with:  bash tools/gen-buildstamp.sh   (tools/build.sh does it automatically)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
OUT=pikachu-moveset/plugin/src/telemetry/buildstamp.rs

SHA=$(git rev-parse --short HEAD 2>/dev/null || echo "nogit")
DIRTY=""
git diff --quiet HEAD -- pikachu-moveset tools 2>/dev/null || DIRTY="+dirty"
WHEN=$(date -u +%Y-%m-%dT%H:%M:%SZ)

cat > "$OUT" <<EOF
// @generated by tools/gen-buildstamp.sh -- DO NOT EDIT
//
// The commit this plugin was built from, logged on the first line of every session so a playtest
// can be tied to the code that produced it. "+dirty" means the tree had uncommitted changes to
// pikachu-moveset/ or tools/ at build time, which is normal mid-round and worth knowing.
pub const BUILD: &str = "$SHA$DIRTY built $WHEN";
EOF
echo "  buildstamp: $SHA$DIRTY $WHEN"
