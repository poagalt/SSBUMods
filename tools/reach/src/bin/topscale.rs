// Scales `top`-anchored hitbox offsets by the source fighter's scale ratio.
//
// tools/anim-dropin.sh corrects for Pikachu's 0.96 `scale` param by scaling the animation's `Rot`
// node, which inherits down every bone -- so a bone-anchored hitbox and its bone-local offset are
// both exact (measured: 0.00 world units on jab, f-smash, n-air and u-air).
//
// A `top`-anchored hitbox never touches the skeleton: `top` is the fighter's origin, so the offset
// is used as-is and then multiplied by the fighter's scale. That path bypasses the animation
// entirely, leaving the ratio uncorrected -- the residual 0.88-1.78 world units that remained on
// dash attack, f-tilt, u-tilt, u-smash and f-air after the animation fix. Correcting it here is
// exact arithmetic, not an approximation: reference = off * source_scale, ours = off * 0.96, so
// off * (source_scale / 0.96) makes the two equal.
//
// HITBOX SIZE IS NOW SCALED TOO, but only on `top`-anchored boxes, and the asymmetry is the point.
//
// The radius was left alone on the grounds that "whether the engine folds in the anchor bone's
// inherited scale is not answerable from the animation data". That is true, and it does not matter
// here, because both possible answers agree on the `top`-anchored case:
//
//   - if radius = size * <the fighter's own scale>, a top-anchored radius is size * 0.96 for us
//     against size * source_scale for the source, so it needs the ratio;
//   - if radius = size * <the anchor bone's inherited world scale>, then for `top` that world
//     scale IS the fighter's scale. `top` is the model root; anim-dropin.sh scales the animation's
//     `Rot` node, which is a DESCENDANT of it, so nothing the drop-in does reaches `top`. Same
//     arithmetic, same conclusion.
//
// So a top-anchored radius is unambiguously off by the scale ratio, and correcting it cannot
// double-count. BONE-anchored radii stay untouched, behind SCALE_BONE_RADII below: that is exactly
// the case where the two answers disagree, and under the second one the animation has already
// fixed them.
//
// GRAB BOXES GO THROUGH THE SAME PATH. `macros::CATCH` has its own argument layout -- no damage or
// knockback block, so bone/size/offsets sit at 2/3/4..9 instead of 3/9/10..15 -- and this pass only
// ever matched `macros::ATTACK`, so Palutena's three top-anchored grab capsules were the one part
// of the moveset with no scale correction at all and no trace row to notice.
//
// NOT IDEMPOTENT: it multiplies the offsets in place, so it must run exactly once, on source
// freshly regenerated by tools/gen-moves.sh. Running it standalone on already-scaled source
// double-scaled the offsets and the hitbox trace reported 0.4-2.1 world units of error.
// tools/build.sh sequences this correctly; do not invoke it by hand.
//
// usage: topscale <plugin-src-dir> [scales.tsv]
