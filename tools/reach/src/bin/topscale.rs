// Whether to apply the scale ratio to BONE-anchored radii as well. This is the one JUDGEMENT CALL
// left in the geometry -- everything else in this file is arithmetic.
//
// The two candidate engine behaviours agree everywhere except here:
//
//   H1  radius = size * <the object's own scale>.  Ours is size * 0.96 against the source's
//       size * source_scale, so bone-anchored radii are 4-20% SMALL and need the ratio.
//   H2  radius = size * <the anchor bone's inherited world scale>.  anim-dropin.sh already put
//       source_scale/0.96 on the `Rot` node, so bone-anchored radii are ALREADY exact and applying
//       the ratio again would make them 4-16% LARGE.
//
// Both give the same answer for the SOURCE fighter, so the reference figure tools/trace-all.sh
// prints is right either way. Only our own side is in question, and only on the nine bone-anchored
// hitboxes it reported 0.11-0.68 world units out: Fox's u-smash knee, Little Mac's f-smash fist,
// Mythra's f-tilt and u-tilt blades, Falco's u-tilt, Corrin's u-air, Palutena's n-air, Kazuya's
// f-air, G&W's up-B and Incineroar's lariat.
//
// SET TRUE, ON H1, for three reasons:
//
//   1. Implementation. A radius is a scalar. An offset rides the bone's world matrix; a radius
//      cannot, so the engine has to multiply it by one object-wide number -- and that number is
//      what `PostureModule::scale` reads and writes. Mods that shrink a character observe the
//      hitboxes shrinking with them. Per-joint scale is used for visual stretching (Min Min's
//      arms, Kirby's copies) and is not believed to resize colliders; if it did, those characters
//      would have ballooning hitboxes and they are authored as though they do not.
//   2. It is the same mechanism this pass already relies on for offsets, and that one is MEASURED:
//      the offset correction brings every position on 36 moves to 0.00 world units, and it works
//      by multiplying by exactly this object scale.
//   3. The magnitude is not in doubt, only the sign. Under H1 this is exact; the cost of being
//      wrong is the same size as the cost of doing nothing, so the tiebreak is which hypothesis is
//      likelier, not which error is cheaper.
//
// TO FALSIFY IT IN ONE LOOK, with a controller: Training Modpack's hitbox visualisation draws the
// real collider. Put modded Pikachu's f-smash beside Little Mac's own and compare each fist bubble
// against its owner. Proportionally the same means H1 and this is right. Pikachu's bubble visibly
// LARGER relative to his body means H2 -- set this false and rebuild, and every radius matches
// under that hypothesis instead. tools/check-hitboxes.sh reports the residual either way, so the
// state of this question stays on screen rather than in someone's memory.
const SCALE_BONE_RADII: bool = true;

// Where the geometry sits in each macro's argument list: (call, bone, size, offsets lo..=hi).
//
//   ATTACK(agent, id, group, bone, damage, angle, kbg, fkb, bkb, size, x, y, z, x2, y2, z2, ...)
//   CATCH (agent, id,        bone, size, x, y, z, x2, y2, z2, status, collision_mask)
//
// ATTACK_ABS is deliberately absent: it carries damage and knockback but no position or radius at
// all, which is why DK's four cargo throws need no correction and have no trace row.
const SHAPES: &[(&str, usize, usize, usize, usize)] = &[
    ("macros::ATTACK(", 3, 9, 10, 15),
    ("macros::CATCH(", 2, 3, 4, 9),
];

// Every mod.rs under the plugin source, at any depth.
fn collect_mods(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect_mods(&p, out);
        } else if p.file_name().map_or(false, |n| n == "mod.rs") {
            out.push(p);
        }
    }
}

// Reads tools/scales.tsv: "fighter	index	scale	weight".
fn load_scales(path: &str) -> HashMap<String, f32> {
    let mut m = HashMap::new();
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("cannot read {path}: {e} -- run tools/gen-scales.sh"));
    for line in text.lines() {
        if line.starts_with('#') { continue }
        let mut f = line.split('\t');
        if let (Some(name), Some(_), Some(sc)) = (f.next(), f.next(), f.next()) {
            if let Ok(v) = sc.trim().parse::<f32>() { m.insert(name.trim().to_string(), v); }
        }
    }
    m
}

// Splits on top-level commas only, so Hash40::new("x") and Some(1.0) stay intact.
fn spans(args: &str) -> Vec<(usize, usize)> {
    let mut out = vec![];
    let mut depth = 0i32;
    let mut start = 0usize;
    for (i, c) in args.char_indices() {
        if c == '(' {
            depth += 1;
        } else if c == ')' {
            depth -= 1;
            if depth < 0 {
                out.push((start, i));
                return out;
            }
        } else if c == ',' && depth == 0 {
            out.push((start, i));
            start = i + 1;
        }
    }
    out.push((start, args.len()));
    out
}

fn fmt(v: f32) -> String {
    if (v - v.round()).abs() < 1e-6 { format!("{:.1}", v) } else { format!("{}", v) }
}

fn main() {
    let src_dir = std::env::args().nth(1).expect("plugin src dir");
    let scales_path = std::env::args().nth(2).unwrap_or_else(|| "tools/scales.tsv".to_string());
    let scales = load_scales(&scales_path);
    let pikachu_scale = *scales.get("pikachu").expect("pikachu missing from scales.tsv");

    // fn -> ratio, resolved once so an unknown fighter fails loudly here rather than silently
    // leaving a move uncorrected.
    let map: HashMap<&str, f32> = MAP
        .iter()
        .map(|(f, fighter)| {
            let s = scales
                .get(*fighter)
                .unwrap_or_else(|| panic!("no scale for '{fighter}' in {scales_path}"));
            (*f, *s / pikachu_scale)
        })
        .collect();
    let mut total = 0usize;
    let mut skipped_bone = 0usize;
    let mut bone_radii = 0usize;

    // RECURSIVE, because one level deep was not enough. The hand-written special ACMDs live at
    // src/specials/acmd/mod.rs and src/specials/acmd_speciallw/mod.rs -- two levels down -- so this
    // pass never even opened them and Game & Watch's up-B hitboxes were left entirely unscaled.
    // Every generated module is one level down, which is why the shallow walk went unnoticed.
    let mut files = Vec::new();
    collect_mods(std::path::Path::new(&src_dir), &mut files);
    for file in files {
        let text = std::fs::read_to_string(&file).unwrap();
        let mut out = String::new();
        let mut cur_fn = String::new();
        let mut changed = 0usize;

        for line in text.lines() {
            if let Some(p) = line.find("unsafe extern \"C\" fn ") {
                cur_fn = line[p + 21..].split('(').next().unwrap_or("").to_string();
            }
            let Some(&ratio) = map.get(cur_fn.as_str()) else { out.push_str(line); out.push('\n'); continue };
            if (ratio - 1.0).abs() < 5e-4 { out.push_str(line); out.push('\n'); continue }
            // Two macros, two layouts. SHAPES is the whole of the difference between them, so
            // adding a third (ATTACK_ABS carries no geometry, so not that one) is one row.
            let Some(&(call, bone_i, size_i, off_lo, off_hi)) = SHAPES
                .iter()
                .find(|(call, ..)| line.contains(*call))
            else { out.push_str(line); out.push('\n'); continue };

            let args_at = line.find(call).unwrap() + call.len();
            let args = &line[args_at..];
            let sp = spans(args);
            if sp.len() <= off_hi { out.push_str(line); out.push('\n'); continue }
            let arg = |n: usize| -> &str { args[sp[n].0..sp[n].1].trim() };

            // Bone-anchored: the offset is already exact via the animation's inherited Rot scale,
            // so only the radius is ever in question -- and only when SCALE_BONE_RADII says so.
            let bone_anchored = arg(bone_i) != "Hash40::new(\"top\")";
            if bone_anchored {
                skipped_bone += 1;
                if !SCALE_BONE_RADII {
                    out.push_str(line); out.push('\n'); continue;
                }
                bone_radii += 1;
            }

            // Rebuild the argument list, scaling the radius, the offset and the stretch endpoints.
            let mut rebuilt: Vec<String> = Vec::with_capacity(sp.len());
            for (n, _) in sp.iter().enumerate() {
                let a = arg(n);
                let scale_this = if bone_anchored {
                    n == size_i
                } else {
                    n == size_i || (off_lo..=off_hi).contains(&n)
                };
                if !scale_this { rebuilt.push(a.to_string()); continue }
                if let Some(inner) = a.strip_prefix("Some(").and_then(|s| s.strip_suffix(")")) {
                    match inner.trim().parse::<f32>() {
                        Ok(v) => rebuilt.push(format!("Some({})", fmt(v * ratio))),
                        Err(_) => rebuilt.push(a.to_string()),
                    }
                } else {
                    match a.parse::<f32>() {
                        Ok(v) => rebuilt.push(fmt(v * ratio)),
                        Err(_) => rebuilt.push(a.to_string()),
                    }
                }
            }
            let tail_start = args_at + sp[sp.len() - 1].1;
            let newline = format!("{}{}{}", &line[..args_at], rebuilt.join(", "), &line[tail_start..]);
            out.push_str(&newline);
            out.push('\n');
            changed += 1;
        }
        if changed > 0 {
            // REFUSE TO EDIT A FILE THAT IS NOT REGENERATED EACH BUILD.
            //
            // This pass multiplies offsets in place and is not idempotent, so it is only safe
            // because gen-moves.sh rewrites its targets from the vanilla dumps first. Making the
            // walk recursive brought a HAND-WRITTEN module into scope and one build turned an
            // offset of 6.0 into 6.2500005; the next would have compounded it, and the only
            // symptom would have been hitboxes drifting further out every rebuild.
            //
            // Every generated module carries the marker below, so this distinguishes them without
            // a second list to keep in step.
            if !text.contains("@generated by tools/gen-moves.sh") {
                eprintln!(
                    "REFUSING: {} is not generated but has {changed} scalable offset(s).\n  \
                     topscale is not idempotent -- a file it edits must be regenerated every build.\n  \
                     Either move these scripts into tools/gen-moves.sh or remove their fns from MAP.",
                    file.display()
                );
                std::process::exit(1);
            }
            std::fs::write(&file, out).unwrap();
            println!("  {:<28} {changed} top-anchored hitboxes scaled",
                     file.parent().unwrap().file_name().unwrap().to_string_lossy());
            total += changed;
        }
    }
    println!("topscale: {total} scaled ({bone_radii} of them bone-anchored radii), \n              {} bone-anchored offset(s) left alone (already exact via the animation)",
             skipped_bone);
}
