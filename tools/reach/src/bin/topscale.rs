// Every mod.rs under the plugin source, at any depth.
fn collect_mods(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect_mods(&p, out);
        } else if p.file_name().map_or(false, |n| n == "mod.rs") {
            out.push(p);
        }
    }
}

// Reads tools/scales.tsv: "fighter	index	scale	weight".
fn load_scales(path: &str) -> HashMap<String, f32> {
    let mut m = HashMap::new();
    let text = std::fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("cannot read {path}: {e} -- run tools/gen-scales.sh"));
    for line in text.lines() {
        if line.starts_with('#') { continue }
        let mut f = line.split('\t');
        if let (Some(name), Some(_), Some(sc)) = (f.next(), f.next(), f.next()) {
            if let Ok(v) = sc.trim().parse::<f32>() { m.insert(name.trim().to_string(), v); }
        }
    }
    m
}

// Splits on top-level commas only, so Hash40::new("x") and Some(1.0) stay intact.
fn spans(args: &str) -> Vec<(usize, usize)> {
    let mut out = vec![];
    let mut depth = 0i32;
    let mut start = 0usize;
    for (i, c) in args.char_indices() {
        if c == '(' {
            depth += 1;
        } else if c == ')' {
            depth -= 1;
            if depth < 0 {
                out.push((start, i));
                return out;
            }
        } else if c == ',' && depth == 0 {
            out.push((start, i));
            start = i + 1;
        }
    }
    out.push((start, args.len()));
    out
}

fn fmt(v: f32) -> String {
    if (v - v.round()).abs() < 1e-6 { format!("{:.1}", v) } else { format!("{}", v) }
}

fn main() {
    let src_dir = std::env::args().nth(1).expect("plugin src dir");
    let scales_path = std::env::args().nth(2).unwrap_or_else(|| "tools/scales.tsv".to_string());
    let scales = load_scales(&scales_path);
    let pikachu_scale = *scales.get("pikachu").expect("pikachu missing from scales.tsv");

    // fn -> ratio, resolved once so an unknown fighter fails loudly here rather than silently
    // leaving a move uncorrected.
    let map: HashMap<&str, f32> = MAP
        .iter()
        .map(|(f, fighter)| {
            let s = scales
                .get(*fighter)
                .unwrap_or_else(|| panic!("no scale for '{fighter}' in {scales_path}"));
            (*f, *s / pikachu_scale)
        })
        .collect();
    let mut total = 0usize;
    let mut skipped_bone = 0usize;

    // RECURSIVE, because one level deep was not enough. The hand-written special ACMDs live at
    // src/specials/acmd/mod.rs and src/specials/acmd_speciallw/mod.rs -- two levels down -- so this
    // pass never even opened them and Game & Watch's up-B hitboxes were left entirely unscaled.
    // Every generated module is one level down, which is why the shallow walk went unnoticed.
    let mut files = Vec::new();
    collect_mods(std::path::Path::new(&src_dir), &mut files);
    for file in files {
        let text = std::fs::read_to_string(&file).unwrap();
        let mut out = String::new();
        let mut cur_fn = String::new();
        let mut changed = 0usize;

        for line in text.lines() {
            if let Some(p) = line.find("unsafe extern \"C\" fn ") {
                cur_fn = line[p + 21..].split('(').next().unwrap_or("").to_string();
            }
            let Some(&ratio) = map.get(cur_fn.as_str()) else { out.push_str(line); out.push('\n'); continue };
            if (ratio - 1.0).abs() < 5e-4 { out.push_str(line); out.push('\n'); continue }
            let Some(ap) = line.find("macros::ATTACK(") else { out.push_str(line); out.push('\n'); continue };

            let args_at = ap + 15;
            let args = &line[args_at..];
            let sp = spans(args);
            if sp.len() < 16 { out.push_str(line); out.push('\n'); continue }
            let arg = |n: usize| -> &str { args[sp[n].0..sp[n].1].trim() };

            if arg(3) != "Hash40::new(\"top\")" {
                // Bone-anchored: already exact via the animation's inherited Rot scale.
                skipped_bone += 1;
                out.push_str(line); out.push('\n'); continue;
            }

            // Rebuild the argument list, scaling x,y,z (10..12) and the stretch endpoints (13..15).
            let mut rebuilt: Vec<String> = Vec::with_capacity(sp.len());
            for (n, _) in sp.iter().enumerate() {
                let a = arg(n);
                let scale_this = (10..=15).contains(&n);
                if !scale_this { rebuilt.push(a.to_string()); continue }
                if let Some(inner) = a.strip_prefix("Some(").and_then(|s| s.strip_suffix(")")) {
                    match inner.trim().parse::<f32>() {
                        Ok(v) => rebuilt.push(format!("Some({})", fmt(v * ratio))),
                        Err(_) => rebuilt.push(a.to_string()),
                    }
                } else {
                    match a.parse::<f32>() {
                        Ok(v) => rebuilt.push(fmt(v * ratio)),
                        Err(_) => rebuilt.push(a.to_string()),
                    }
                }
            }
            let tail_start = args_at + sp[sp.len() - 1].1;
            let newline = format!("{}{}{}", &line[..args_at], rebuilt.join(", "), &line[tail_start..]);
            out.push_str(&newline);
            out.push('\n');
            changed += 1;
        }
        if changed > 0 {
            // REFUSE TO EDIT A FILE THAT IS NOT REGENERATED EACH BUILD.
            //
            // This pass multiplies offsets in place and is not idempotent, so it is only safe
            // because gen-moves.sh rewrites its targets from the vanilla dumps first. Making the
            // walk recursive brought a HAND-WRITTEN module into scope and one build turned an
            // offset of 6.0 into 6.2500005; the next would have compounded it, and the only
            // symptom would have been hitboxes drifting further out every rebuild.
            //
            // Every generated module carries the marker below, so this distinguishes them without
            // a second list to keep in step.
            if !text.contains("@generated by tools/gen-moves.sh") {
                eprintln!(
                    "REFUSING: {} is not generated but has {changed} scalable offset(s).\n  \
                     topscale is not idempotent -- a file it edits must be regenerated every build.\n  \
                     Either move these scripts into tools/gen-moves.sh or remove their fns from MAP.",
                    file.display()
                );
                std::process::exit(1);
            }
            std::fs::write(&file, out).unwrap();
            println!("  {:<28} {changed} top-anchored hitboxes scaled",
                     file.parent().unwrap().file_name().unwrap().to_string_lossy());
            total += changed;
        }
    }
    println!("topscale: {total} scaled, {skipped_bone} bone-anchored left alone (already exact)");
}
