#!/usr/bin/env bash
# Ships the moveset's animations for RAT OF DOOM'S costume(s) and retires them from everyone else's.
#
# THIS SCRIPT USED TO DO THE OPPOSITE, and the reversal is the point. It copied
# `motion/body/c00` into c01..c07 so that "the moves work on every colour" -- written when the
# moveset simply WAS Pikachu and a player on c05 got a half-broken character. Rat of Doom is now its
# own slot (`plugin/src/charaslot`), so animations on the other seven costumes are not a feature,
# they are the bug: they replace 45 of vanilla Pikachu's own animations on colours he is supposed
# to still own. Mirroring them is now exactly the regression the model mirror was always refused for.
#
# WHAT IS SHIPPED, AND WHAT DELIBERATELY IS NOT.
#
#   motion/body/<rat slot>           YES -- generated by anim-dropin.sh, which writes c00.
#
#   motion/body/<every other slot>   RETIRED. Removed from the tree here so deploy.sh's retire list
#                                    takes them off the card too. A left-behind directory is the
#                                    shipped-but-undeclared trap: ARCropolis would go on serving
#                                    Rat of Doom's animations to a vanilla Pikachu from files no
#                                    build step mentions any more.
#
#   model/body/<rat slot>            c00 only, and that is WHY c00 is the slot. Each costume's body
#                                    model carries its own textures, so there is exactly one costume
#                                    the grafted weapons can live on without turning other Pikachus
#                                    default yellow -- see the note in plugin/src/charaslot/mod.rs.
#
# THE SLOT NUMBER IS NOT THIS PASS'S BUSINESS ANY MORE. It briefly was, when Rat of Doom took one
# of Pikachu's own eight colours. He now takes an ADDED slot, so the authoring tree stays in the
# host's coordinate system -- c00 throughout -- and `tools/relocate-slot.sh` moves the whole thing
# onto the added colour at the end of the build. This pass only has to make sure the authoring tree
# holds c00 and nothing else.
#
# `motion_list.bin` IS SHIPPED WITH IT, AND THAT WAS CHECKED RATHER THAN ASSUMED. It is the thing
# that makes the 30 synthesized motions resolvable at all (`src/specials/mod.rs`: "they are
# synthesized into motion_list.bin by ..."), and vanilla has a separate copy in all eight costume
# directories. Pulled c00, c01, c04 and c07 out of the archive and compared: 43,428 bytes and md5
# c9ddb186ce85318e1abaa25832dd0b08, all four identical -- so the per-costume copies are the same
# file, and retiring seven of them restores exactly what vanilla had.
#
# THE FILENAMES LOOK LIKE COSTUMES AND ARE NOT. `c00attack11.nuanmb`, `c01attacks3s.nuanmb`,
# `b02escapeair.nuanmb` -- the leading letter and two digits are SSBU's animation-GROUP naming,
# which is why 23 of the shipped files carry one and why they are copied verbatim rather than
# renamed per costume. Renaming them would break every one.
#
# Runs from build.sh after anim-dropin.sh, which regenerates c00 on every build. Idempotent.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BODY="$ROOT/pikachu-moveset/mod/fighter/pikachu/motion/body"
SRC="$BODY/c00"
if [ ! -d "$SRC" ]; then
    echo "  no c00 motion directory -- run tools/anim-dropin.sh first" >&2
    exit 1
fi
n_src=$(find "$SRC" -maxdepth 1 -type f | wc -l)
if [ "$n_src" -lt 10 ]; then
    echo "  REFUSING: c00 has only $n_src file(s), which is not a built animation set" >&2
    exit 1
fi

# RETIRING IS A WIPE, and that is equivalent to the old per-file retire pass rather than a shortcut
# past it: nothing in `motion/body/cNN` is costume-specific for this mod, so the whole directory is
# ours or it is vanilla's. Removing it is the only way to hand the colour back.
retired=0
for c in c01 c02 c03 c04 c05 c06 c07; do
    [ -d "$BODY/$c" ] || continue
    rm -rf "$BODY/$c"
    retired=$(( retired + 1 ))
done

if [ "$retired" -gt 0 ]; then
    echo "  retired $retired costume(s) from motion/body -- the authoring tree holds c00 alone"
else
    echo "  motion/body holds c00 alone ($n_src animation(s)); nothing to retire"
fi
