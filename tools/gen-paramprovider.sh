#!/usr/bin/env bash
# Generates the param table src/params/mod.rs answers with, from Incineroar's own vl.prc.
#
# WHY GENERATED AND NOT TYPED. The table started as twelve rows typed by hand -- the twelve the
# VICTIM's status reads, disassembled out of lua2cpp_common -- with a comment explaining that
# Incineroar's other thirty-eight were read by HIS native code, which never runs for a Pikachu, so
# providing them would create a second copy of a number nothing reads.
#
# That stopped being true the moment the whip was rewritten as a transcription. `FUN_710001d4b0`,
# the kinetic setup every one of his six side-B statuses calls, reads eight more --
# special_s_start_speed_mul, special_air_s_start_speed_mul, special_air_s_catch_accel_y,
# special_air_s_catch_speed_y_max, special_s_catch_speed_x_mul, special_s_catch_brake_x and both
# air catch equivalents -- and a transcription of it running on a Pikachu reads them off PIKACHU.
# Every one would have come back 0.
#
# So the provider answers the WHOLE object, and the table is generated from the prc rather than
# transcribed, because fifty hand-typed floats is fifty chances to typo a value that then looks
# like a physics bug. `tools/check.sh` step 3e2 checks every row against the same prc afterwards,
# which is now a check that the generator ran rather than that someone typed carefully.
#
# The int/float split is the prc's own: vlkeys reports each key's type, so `special_s_catch_frame`
# does not become a float because it happens to look like one.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
PRC="extracted/fighter/gaogaen/param/vl.prc"
DUMP=tools/prc-tool/target/release/prcdump.exe
OUT=pikachu-moveset/plugin/src/params/table.rs

[ -f "$PRC" ] || { echo "no extracted gaogaen vl.prc" >&2; exit 1; }

# param_special_s is a list[4] whose [0] is the real struct; [1..3] are zeroed per-slot copies.
rows="$("$DUMP" "$PRC" vendor/param-labels/ParamLabels.csv 2>/dev/null \
        | awk 'index($0,"  param_special_s ")==1{f=1;next} f&&/^  [a-z0-9_]+ /{f=0} f' \
        | awk '/^    \[0\]/{p=1;next} /^    \[[1-9]\]/{p=0} p' \
        | sed 's/^ *//')"

h40() {
    perl -e '
        my @t; for my $i (0..255){ my $c=$i; for(1..8){ $c=($c&1)?(0xEDB88320^($c>>1)):($c>>1); } $t[$i]=$c; }
        my $s = $ARGV[0]; my $c = 0xFFFFFFFF;
        for my $b (unpack("C*", $s)) { $c = $t[($c ^ $b) & 0xFF] ^ ($c >> 8); }
        $c ^= 0xFFFFFFFF;
        printf "0x%x_%04x_%04x\n", length($s), ($c >> 16) & 0xffff, $c & 0xffff;
    ' "$1"
}

{
    cat <<'HDR'
// GENERATED by tools/gen-paramprovider.sh from extracted/fighter/gaogaen/param/vl.prc.
// Do not edit. Re-run the generator.
//
// Incineroar's whole `param_special_s`, as hash40 of the key to the value in his prc. See
// src/params/mod.rs for what answers with it and why it is the whole object rather than the
// twelve keys the victim reads.
HDR
    printf '\npub static INTS: &[(u64, i32, &str)] = &[\n'
    printf '%s\n' "$rows" | while IFS= read -r row; do
        name="${row%% =*}"; value="${row##*= }"
        case "$name" in 0x*) continue ;; esac
        # A value with no decimal point and no exponent is an int in this object.
        case "$value" in
          *.*|*e*) continue ;;
          -*|[0-9]*) printf '    (%s, %s, "%s"),\n' "$(h40 "$name")" "$value" "$name" ;;
          *) continue ;;
        esac
    done
    printf '];\n\npub static FLOATS: &[(u64, f32, &str)] = &[\n'
    printf '%s\n' "$rows" | while IFS= read -r row; do
        name="${row%% =*}"; value="${row##*= }"
        case "$name" in 0x*) continue ;; esac
        case "$value" in
          *.*) printf '    (%s, %s, "%s"),\n' "$(h40 "$name")" "$value" "$name" ;;
          *) continue ;;
        esac
    done
    printf '];\n'
} > "$OUT"

# NO TABLE MAY EXCEED 64 ROWS. src/params dedupes its "the engine asked for X" lines with one bit
# per row in a u64, and the release build has no overflow-checks, so a 65th row would silently
# alias row 0 and suppress one of the two announcements -- which is exactly the bug the bitsets
# had while they were u16 against a 32-row table. Refused here, where the table is made.
for tbl in $(sed -n 's/^pub static \([A-Z_]*\):.*/\1/p' "$OUT"); do
    rows=$(awk -v t="pub static $tbl:" 'index($0,t)==1{f=1;next} f&&/^\];/{exit} f&&/^    \(0x/{n++} END{print n+0}' "$OUT")
    if [ "$rows" -gt 64 ]; then
        echo "REFUSING: $tbl has $rows rows; src/params/mod.rs tracks at most 64 per table" >&2
        exit 1
    fi
done

echo "  wrote $OUT: $(grep -c '^    (0x' "$OUT") param(s)"

# THE ROPE'S OWN OBJECT, `param_rope`, into a file of its own (gate 3e2 checks table.rs against
# param_special_s and nothing else). The rope's Bend status reads `bend_time` off ITSELF through
# WorkModule -- the frame it lets the victim go and jumps to the rebound -- and a clone owned by
# Pikachu has nothing behind it, so the read would be 0: a release on the bend's first frame. One
# table for either accessor, the way src/params/ptooie.rs carries the spikeball's.
ROPE_OUT=pikachu-moveset/plugin/src/params/rope.rs
rope_rows="$("$DUMP" "$PRC" vendor/param-labels/ParamLabels.csv 2>/dev/null \
        | awk 'index($0,"  param_rope ")==1{f=1;next} f&&/^  [a-z0-9_]+ /{f=0} f' \
        | awk '/^    \[0\]/{p=1;next} /^    \[[1-9]\]/{p=0} p' \
        | sed 's/^ *//')"
[ -n "$rope_rows" ] || { echo "no param_rope in $PRC" >&2; exit 1; }
{
    cat <<'HDR'
// GENERATED by tools/gen-paramprovider.sh from extracted/fighter/gaogaen/param/vl.prc.
// Do not edit. Re-run the generator.
//
// Incineroar's `param_rope` [0], which his ROPE reads off itself (its Bend status's `bend_time`),
// answered by src/params for a Rat of Doom's rope. Numbers only; `attach_area_node` is a hash
// and read by nothing the port runs.
HDR
    printf '\npub static ROPE: &[(u64, f32, &str)] = &[\n'
    printf '%s\n' "$rope_rows" | while IFS= read -r row; do
        name="${row%% =*}"; value="${row##*= }"
        case "$name" in 0x*) key="$(printf '0x%s_%s_%s' "$(echo "${name#0x}" | cut -c1-4 | sed 's/^0*//;s/^$/0/')" "$(echo "${name#0x}" | cut -c5-8)" "$(echo "${name#0x}" | cut -c9-12)")" ;; *) key="$(h40 "$name")" ;; esac
        case "$value" in
          -*|[0-9]*)
            case "$value" in *.*|*e*) v="$value" ;; *) v="$value.0" ;; esac
            printf '    (%s, %s, "%s"),\n' "$key" "$v" "$name" ;;
          *) continue ;;
        esac
    done
    printf '];\n'
} > "$ROPE_OUT"
echo "  wrote $ROPE_OUT: $(grep -c '^    (0x' "$ROPE_OUT") param(s)"
