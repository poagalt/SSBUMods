#!/usr/bin/env bash
# Generates the motion table the in-game self-test walks.
#
# WHY A GENERATOR AND NOT A HAND-WRITTEN LIST. tools/ported-motions.txt is already the one list of
# what this moveset replaces, and every previous copy of it drifted -- three copies once, and the
# effects were `throw_f` outside the dropin pre-flight and the blend audit running on nothing. A
# self-test that walks a stale list would report a clean bill of health for motions the mod no
# longer ships and say nothing about ones it added, which is worse than having no self-test.
#
# Regenerate with:  bash tools/gen-selftest.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/pikachu-moveset/plugin/src/telemetry/motions.rs"
SRC="$ROOT/tools/ported-motions.txt"

# `fighter:motion` -> motion, deduplicated. A motion can only have one entry in Pikachu's
# motion_list no matter how many sources contribute to a family, so duplicates here would just
# check the same thing twice.
motions=$(grep -vE '^\s*#|^\s*$' "$SRC" | cut -d: -f2 | sort -u)
n=$(echo "$motions" | wc -l | tr -d ' ')

{
cat <<'HEADER'
// @generated by tools/gen-selftest.sh -- DO NOT EDIT
//
// Every motion this moveset replaces or synthesises, for the in-game self-test in selftest.rs to
// ask the game about one at a time. Derived from tools/ported-motions.txt, which is the single
// list of what the mod ships; see that file for why there is exactly one.
HEADER
echo "pub const PORTED_MOTIONS: &[&str] = &["
echo "$motions" | sed 's/^/    "/; s/$/",/'
echo "];"
} > "$OUT"

echo "  wrote motions.rs: $n ported motion(s)"
