#!/usr/bin/env bash
# The three hand-maintained port lists must agree with each other.
#
# THEY HAVE DRIFTED THREE TIMES AND EVERY TIME IT COST A PLAYTEST ROUND.
#
#   tools/gen-moves.sh          inline NORMALS/SPECIALS/... tables -- what actually GENERATES
#   tools/moves.tsv             the manifest the CHECKS read
#   tools/reach topscale MAP    generated fn -> source fighter, for scaling top-anchored offsets
#
# Drift in each direction has a different and equally quiet failure:
#   * in gen-moves.sh only  -> the script exists but is never measured by check-hitboxes
#   * in moves.tsv only     -> nothing is generated; I wrote two commit messages claiming a script
#                              was missing when it was present, because I read moves.tsv and not
#                              the generated file
#   * missing from MAP      -> the script is generated and measured and its top-anchored offsets
#                              are at the SOURCE's scale, which is the 0.44-world-unit signature
#
# Only the third was ever caught automatically, and only via moves.tsv, which is the list nothing
# enforced. This is that enforcement.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
rc=0

# gen-moves.sh rows are `label|fighter|AcmdFile|fname`, and `N|-` marks a deliberate empty
# override -- those have no source and belong in no other list.
gen=$(grep -hoE '^[^|#]+\|[a-z0-9]+\|[A-Za-z0-9]+\|[a-z0-9]+$' tools/gen-moves.sh \
      | awk -F'|' '$2!="N"{print $2"\t"$3"\t"$4}' | sort -u)
# WHITESPACE, NOT TABS. `tools/moves.tsv` is tab-NAMED and space-ALIGNED: its original rows are
# padded with spaces and the rows appended since are tab-separated. Every existing reader uses a
# bare `read -r f acmd fn ...` with the default IFS, which handles both; the first draft of this
# check used `awk -F'\t'` and reported all twenty-five original rows as missing.
tsv=$(grep -vE '^[[:space:]]*(#|$)' tools/moves.tsv \
      | awk 'NF>=3{print $1"\t"$2"\t"$3}' | sort -u)

only_gen=$(comm -23 <(printf '%s\n' "$gen") <(printf '%s\n' "$tsv"))
only_tsv=$(comm -13 <(printf '%s\n' "$gen") <(printf '%s\n' "$tsv"))

if [ -n "$only_gen" ]; then
    echo "  FAIL generated by gen-moves.sh but absent from tools/moves.tsv, so never measured:"
    printf '%s\n' "$only_gen" | sed 's/^/       /'
    rc=1
fi
if [ -n "$only_tsv" ]; then
    echo "  FAIL listed in tools/moves.tsv but not generated by gen-moves.sh, so the manifest"
    echo "       claims a port that does not exist:"
    printf '%s\n' "$only_tsv" | sed 's/^/       /'
    rc=1
fi

# Every generated game_ fn that places a hitbox on `top` must be in topscale's MAP, or its offsets
# and radii stay at the source fighter's scale.
mapped=$(grep -oE '\("pikachu_game_[a-z0-9]+", "[a-z0-9]+"\)' tools/reach/src/bin/topscale.rs \
         | sed 's/.*"pikachu_game_\([a-z0-9]*\)".*/\1/' | sort -u)
unscaled=""
for f in $(grep -rhoE 'unsafe extern "C" fn pikachu_game_[a-z0-9]+' pikachu-moveset/plugin/src/ \
           | sed 's/.*pikachu_game_//' | sort -u); do
    # Only the ones that actually anchor a hitbox to `top`.
    awk -v f="pikachu_game_$f" '
        index($0, "fn " f "(") { inside = 1 }
        inside && /Hash40::new\("top"\)/ { found = 1 }
        inside && /^}/ { inside = 0 }
        END { exit !found }
    ' $(grep -rl "fn pikachu_game_$f(" pikachu-moveset/plugin/src/) || continue
    printf '%s\n' "$mapped" | grep -qx "$f" || unscaled="$unscaled $f"
done
if [ -n "$unscaled" ]; then
    echo "  FAIL these generated scripts put a hitbox on \`top\` and are not in topscale's MAP,"
    echo "       so their offsets and radii are at the SOURCE fighter's scale:$unscaled"
    rc=1
fi

[ $rc -eq 0 ] && echo "  ok  gen-moves.sh, tools/moves.tsv and topscale's MAP agree ($(printf '%s\n' "$gen" | wc -l) ported script(s))"
exit $rc
