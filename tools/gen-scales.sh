#!/usr/bin/env bash
# Generates tools/scales.tsv: every fighter's `scale` param, read from the game's own
# fighter_param.prc via each entry's `fighter_kind` field.
#
# These were hand-entered in three places (anim-dropin.sh, topscale.rs, moves.tsv) and two were
# wrong: Cloud 1.03 against an actual 0.98, and K. Rool 1.15 against an actual 0.89 -- a 29%
# over-scale on his d-air. The hitbox trace reported 0.00 error throughout, because it used the
# same wrong constant on both sides of the comparison. A trace can only prove consistency; it
# cannot audit its own inputs. So the inputs now come from the game.
#
# The table is NOT ordered by anything guessable -- index 19 is Pichu, not Falco -- so the mapping
# comes from the `fighter_kind` hash40 each entry carries.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/tools/scales.tsv"
PRC="$ROOT/extracted/fighter/common/param/fighter_param.prc"
LBL="$ROOT/vendor/param-labels/ParamLabels.csv"

[ -f "$PRC" ] || { echo "no fighter_param.prc at $PRC" >&2; exit 1; }
{
  echo "# generated by tools/gen-scales.sh -- DO NOT EDIT BY HAND"
  echo "# fighter	index	scale	weight"
  "$ROOT/tools/prc-tool/target/release/fscale.exe" "$PRC" "$LBL" \
    | tail -n +3 | awk 'NF==4 {printf "%s\t%s\t%s\t%s\n", $1, $2, $3, $4}' | sort
} > "$OUT"
echo "wrote $OUT ($(grep -vc '^#' "$OUT") fighters)"
