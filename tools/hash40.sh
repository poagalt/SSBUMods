#!/usr/bin/env bash
# Resolves a hash40 to a name, or a name to its hash40.
#
#   bash tools/hash40.sh 0x8af9b3d1d          what is this hash?
#   bash tools/hash40.sh shoulder             what does this name hash to?
#   bash tools/hash40.sh --len 19             every known name of that length
#
# WHY THREE SOURCES, AND WHY NONE OF THEM IS ENOUGH ALONE. Half of what the game's status code
# passes around is a hash40 and nothing else -- `LinkModule::send_event_nodes(boma,
# LINK_NO_CAPTURE, 0x8af9b3d1d, 0)` is how Donkey Kong tells the fighter on his shoulder to be
# carried -- so every one of these has to be resolved before the call can be reproduced.
#
#   vendor/Hashes.txt            149,871 community names: file paths, motions, params. This is
#                                where "shoulder", "throw_f_f" and "thrown_f_donkey_f" came from.
#   vendor/param-labels          the prc label list, same shape.
#   vendor/main/hash40-dict.txt  47,856 hashes of every identifier-like string in main's .rodata
#                                and .text, generated by `luaconst --hashdict`. This is where
#                                `owner_object_id_` and `reaction_max_` came from -- C++ member
#                                names exposed into L2C tables, which no community list has and no
#                                amount of guessing at plausible spellings would have produced.
#
# A hash in NONE of them is one the L2C compiler baked at build time from a string that is not in
# the executable. Those are guessable -- the naming is regular, and a candidate is CONFIRMED by
# hashing it rather than argued for -- and `--len` narrows the guess to the right length, because
# hash40 carries the length in its top byte.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"

NAMES=work/hash40-names.txt
# Rebuilt only when a source is newer, because it is 4 MB of sorting.
if [ ! -s "$NAMES" ] \
   || [ vendor/Hashes.txt -nt "$NAMES" ] \
   || [ vendor/param-labels/ParamLabels.csv -nt "$NAMES" ] \
   || [ vendor/main/hash40-confirmed.txt -nt "$NAMES" ]; then
    mkdir -p work
    { cat vendor/Hashes.txt
      awk -F, 'NF>1 {print $2}' vendor/param-labels/ParamLabels.csv
      # Every motion, effect and sound name that appears as a `Hash40::new("...")` literal in the
      # dumped vanilla ACMD scripts -- 14,629 of them, in the game's own spelling.
      grep -rho 'Hash40::new("[a-z0-9_]*")' vendor/SSBU-Dumped-Scripts 2>/dev/null \
        | sed 's/Hash40::new("//; s/")//'
      # And the names this project confirmed by hash because nothing else had them.
      sed 's/#.*//' vendor/main/hash40-confirmed.txt 2>/dev/null
    } | tr -d '\r' | sed 's/[[:space:]]*$//' | sed '/^$/d' | sort -u > "$NAMES"
fi

hash_of() {
    perl -e '
        my @t; for my $i (0..255){ my $c=$i; for(1..8){ $c=($c&1)?(0xEDB88320^($c>>1)):($c>>1); } $t[$i]=$c; }
        my $s = $ARGV[0];
        my $c = 0xFFFFFFFF;
        for my $b (unpack("C*", $s)) { $c = $t[($c ^ $b) & 0xFF] ^ ($c >> 8); }
        $c ^= 0xFFFFFFFF;
        printf "0x%x%08x\n", length($s), $c;
    ' "$1"
}

case "${1:-}" in
  "")
    echo "usage: hash40.sh <0xHASH> | <name> | --len <n>" >&2; exit 2 ;;
  --len)
    n="${2:?--len needs a length}"
    awk -v n="$n" 'length($0) == n' "$NAMES" | head -60
    echo "  ($(awk -v n="$n" 'length($0) == n' "$NAMES" | wc -l) name(s) of length $n known)" ;;
  0x*)
    # ONE perl process for the whole search, not one per candidate. A name-at-a-time loop spawns
    # a process per guess, and on this machine that is 60 ms each -- minutes for the few thousand
    # names of a given length, for an answer that takes milliseconds inside a single interpreter.
    perl -e '
        my @t; for my $i (0..255){ my $c=$i; for(1..8){ $c=($c&1)?(0xEDB88320^($c>>1)):($c>>1); } $t[$i]=$c; }
        sub h40 { my $s=shift; my $c=0xFFFFFFFF;
                  for my $b (unpack("C*",$s)){ $c=$t[($c^$b)&0xFF]^($c>>8); }
                  $c ^= 0xFFFFFFFF; return sprintf("0x%x%08x", length($s), $c); }
        my ($want, $names, $dict) = @ARGV;
        $want = lc $want;
        my $body = $want; $body =~ s/^0x//;
        my $len = hex(substr($body, 0, length($body) - 8));
        open(my $n, "<", $names) or die "no names file: $!";
        while (my $l = <$n>) {
            chomp $l; $l =~ s/\s+$//;
            next unless length($l) == $len;
            if (h40($l) eq $want) { print "$want  $l   (name list)\n"; exit 0 }
        }
        close $n;
        if (open(my $d, "<", $dict)) {
            while (my $l = <$d>) {
                if ($l =~ /^\Q$want\E\s+(.+)$/) { print "$want  $1   (main own strings)\n"; exit 0 }
            }
        }
        print "$want  UNRESOLVED -- the name is $len characters.\n";
        print "  Every source has been searched. The L2C compiler baked this one from a string\n";
        print "  that is not in the executable or the archive, so it has to be guessed and then\n";
        print "  CONFIRMED: bash tools/hash40.sh <guess>, and record a hit in\n";
        print "  vendor/main/hash40-confirmed.txt. Narrow the guess with --len $len.\n";
        exit 1;
    ' "$1" "$NAMES" vendor/main/hash40-dict.txt ;;
  *)
    echo "$(hash_of "$1")  $1" ;;
esac
